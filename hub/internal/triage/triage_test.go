func TestTokensAndJaccard(t *testing.T) {
	if got := Tokens("The relay's status clears, the errors!"); !reflect.DeepEqual(got, []string{"clears", "errors", "relay", "status"}) {
		t.Fatalf("tokens %v", got)
	}
	if got := Similarity("Relay status clears errors", "relay status clears old errors"); got != 0.8 {
		t.Fatalf("similarity %v", got)
	}
	if Jaccard(nil, []string{"a"}) != 0 {
		t.Fatal("empty set scored")
	}
}

func TestCriteriaLines(t *testing.T) {
	description := "Intro text.\n\nAcceptance:\n- c1: queue ownership from intake\n- a2 (c1): unscoped add refused\n**b3.** handler briefing\nnot a criterion: prose"
	got := Criteria(description)
	want := []string{"queue ownership from intake", "unscoped add refused", "handler briefing"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("criteria %q", got)
	}
	if CriteriaSimilarity(description, "no criteria here") != 0 {
		t.Fatal("criteria scored against a description without criteria")
	}
}

func TestReleaseRows(t *testing.T) {
	record := "# Release\n\n| Tasks-hub | Item | What it does |\n|---|---|---|\n| `abc1234` | Relay status (`wi_3a2b456f2e997eb4`) | `tt relay --status` clears errors |\n| `def5678` | Docs | Task docs |\n\nText\n\n| A | B |\n|---|---|\n| x | y |\n"
	rows := ReleaseRows(record)
	if len(rows) != 3 || !reflect.DeepEqual(rows[0].ItemIDs, []string{"wi_3a2b456f2e997eb4"}) || rows[0].Cells[2] != "`tt relay --status` clears errors" || rows[2].Text != "x y" {
		t.Fatalf("rows %+v", rows)
	}
}

type goldenItem struct{ title, description string }

// pairScore is one scored pair: A and B index the open (and done) fixture.
type pairScore struct {
	A, B            int
	Title, Criteria float64
}

// goldenOpen and goldenDone cover a title-only and a criteria-only duplicate,
// a pair over both thresholds, near misses, items without criteria, criteria
// with no tokens and an open item a done item delivered by criteria only.
var goldenOpen = []goldenItem{
	{"Relay status clears stale errors", "The relay keeps old errors after a reconnect."},
	{"Relay status clears old errors", "Seen again today.\n- c1: errors stay visible\n- c2: nothing else"},
	{"Queue ownership comes from intake", "Acceptance:\n- c1: queue ownership from intake\na2 (c1): unscoped add refused\n**b3.** handler briefing names the owner"},
	{"Handler briefing for scoped adds", "Criteria:\n* a1: Queue ownership from intake.\n- b2 (a1): unscoped add refused\n**c3.** Handler briefing names the owner"},
	{"Steward wake skips paused projects", "- t1: paused projects get no wake\n- t2: the wake log names the skip"},
	{"Steward wake skips paused project", "- t1: paused projects get no wake\n- t2: wake log names the skip"},
	{"Deployer retries load failures", "- d1: a load failure retries once\n- d2: the checkout is restored"},
	{"Deployer retries load errors twice", "- d1: the a\n- d2: x y"},
	{"Triage tokens per item", "- t1: tokens computed once per item\n- t2: same output as before"},
}

var goldenDone = []goldenItem{
	{"Precompute triage scores", "Shipped.\n- a1: tokens computed once per item\n- a2: same output as before"},
	{"Relay reconnect backoff", "- r1: backoff doubles to a cap"},
	{"Deployer retry policy", "- r1: a load failure retries twice\n- r2: checkout kept"},
}

// referencePairs is the store's pair scoring as it was before profiles:
// every open pair, then every open item against every done item.
func referencePairs(open, done []goldenItem) (dups, delivered []pairScore) {
	for i := range open {
		for j := i + 1; j < len(open); j++ {
			title := Similarity(open[i].title, open[j].title)
			criteria := CriteriaSimilarity(open[i].description, open[j].description)
			if title >= TitleThreshold || criteria >= CriteriaThreshold {
				dups = append(dups, pairScore{i, j, title, criteria})
			}
		}
	}
	for i := range open {
		for j := range done {
			title := Similarity(open[i].title, done[j].title)
			criteria := CriteriaSimilarity(open[i].description, done[j].description)
			if title >= TitleThreshold || criteria >= CriteriaThreshold {
				delivered = append(delivered, pairScore{i, j, title, criteria})
			}
		}
	}
	return dups, delivered
}

// Generated by referencePairs at tasks-hub be9ca4fc, before profiles.
var (
	goldenDuplicates = []pairScore{
		{0, 1, 0.6666666666666666, 0},
		{2, 3, 0, 1},
		{4, 5, 0.6666666666666666, 1},
	}
	goldenDelivered = []pairScore{
		{8, 0, 0.16666666666666666, 1},
	}
)

func TestGoldenPairs(t *testing.T) {
	dups, delivered := referencePairs(goldenOpen, goldenDone)
	if !reflect.DeepEqual(dups, goldenDuplicates) || !reflect.DeepEqual(delivered, goldenDelivered) {
		t.Fatalf("reference duplicates %v delivered %v", dups, delivered)
	}
	profiles := func(items []goldenItem) []Profile {
		out := make([]Profile, len(items))
		for i, it := range items {
			out[i] = NewProfile(it.title, it.description)
		}
		return out
	}
	scores := func(matches []Match) []pairScore {
		var out []pairScore
		for _, m := range matches {
			out = append(out, pairScore{m.A, m.B, m.Title, m.Criteria})
		}
		return out
	}
	open, done := profiles(goldenOpen), profiles(goldenDone)
	if got := scores(Duplicates(open)); !reflect.DeepEqual(got, goldenDuplicates) {
		t.Fatalf("duplicates %v, want %v", got, goldenDuplicates)
	}
	if got := scores(Delivered(open, done)); !reflect.DeepEqual(got, goldenDelivered) {
		t.Fatalf("delivered %v, want %v", got, goldenDelivered)
	}
	items, all := append(append([]goldenItem{}, goldenOpen...), goldenDone...), append(append([]Profile{}, open...), done...)
	for i := range items {
		for j := range items {
			if title := Jaccard(all[i].title, all[j].title); title != Similarity(items[i].title, items[j].title) {
				t.Fatalf("items %d/%d title %v", i, j, title)
			}
			if criteria := Jaccard(all[i].criteria, all[j].criteria); criteria != CriteriaSimilarity(items[i].description, items[j].description) {
				t.Fatalf("items %d/%d criteria %v", i, j, criteria)
			}
		}
	}
}
