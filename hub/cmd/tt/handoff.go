func handoffIn(value string, list []string) bool {
	for _, v := range list {
		if v == value {
			return true
		}
	}
	return false
}

// handoffListed is value when the list holds it and "other" otherwise. It is
// for values tt did not choose: Claude Code's and the hub's.
func handoffListed(value string, list []string) string {
	if handoffIn(value, list) {
		return value
	}
	return handoffOther
}

func handoffID(value, prefix string) bool {
	return handoffHexIDPattern.MatchString(value) && strings.HasPrefix(value, prefix+"_")
}

func handoffStamped(t time.Time) string { return t.UTC().Format(handoffTimeLayout) }

func handoffTimeOK(value string) bool {
	if !handoffTimePattern.MatchString(value) {
		return false
	}
	_, err := time.Parse(handoffTimeLayout, value)
	return err == nil
}

// handoffParseTime accepts an RFC 3339 time and stores it in UTC to the
// second. Nothing else is a time.
func handoffParseTime(value string) (string, error) {
	t, err := time.Parse(time.RFC3339, value)
	if err != nil || len(value) > 40 || t.Year() < 2000 || t.Year() > 9999 {
		return "", errors.New("is not an RFC 3339 time, such as 2026-10-08T04:00:00Z")
	}
	return handoffStamped(t), nil
}

// handoffParseExpiry accepts a time, "none", or a duration from now.
func handoffParseExpiry(value string) (string, error) {
	if value == handoffNone {
		return handoffNone, nil
	}
	if len(value) <= 16 {
		if d, err := time.ParseDuration(value); err == nil {
			if d <= 0 || d > 366*24*time.Hour {
				return "", errors.New("is not a duration between 1s and 8784h")
			}
			return handoffStamped(handoffNow().Add(d)), nil
		}
	}
	if stamp, err := handoffParseTime(value); err == nil {
		return stamp, nil
	}
	return "", errors.New("is not an RFC 3339 time, a duration such as 12h, or none")
}

// handoffParseSchedule accepts a five-field cron schedule whose fields are
// numbers, ranges, lists and steps inside each field's range, and stores it
// with single spaces. Names such as MON are refused: a schedule holds no
// letters.
func handoffParseSchedule(value string) (string, error) {
	bad := errors.New("is not a five-field cron schedule of numbers, ranges, lists and steps within range, such as '0 * * * *'")
	if len(value) > 64 {
		return "", bad
	}
	fields := strings.Fields(value)
	if len(fields) != 5 {
		return "", bad
	}
	for i, r := range [5][2]int{{0, 59}, {0, 23}, {1, 31}, {1, 12}, {0, 7}} {
		for _, part := range strings.Split(fields[i], ",") {
			base, step, stepped := strings.Cut(part, "/")
			if stepped {
				if n, ok := handoffCronNumber(step); !ok || n < 1 || n > r[1] {
					return "", bad
				}
			}
			if base == "*" {
				continue
			}
			low, high, ranged := strings.Cut(base, "-")
			a, ok := handoffCronNumber(low)
			if !ok || a < r[0] || a > r[1] {
				return "", bad
			}
			if ranged {
				if b, ok := handoffCronNumber(high); !ok || b < a || b > r[1] {
					return "", bad
				}
			}
		}
	}
	return strings.Join(fields, " "), nil
}

func handoffCronNumber(s string) (int, bool) {
	if len(s) == 0 || len(s) > 2 {
		return 0, false
	}
	for i := 0; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return 0, false
		}
	}
	n, err := strconv.Atoi(s)
	return n, err == nil
}

// handoffSetField validates one note field and stores it. The value is
// refused unless it is exactly one of the validated kinds; nothing is cut,
// trimmed or otherwise repaired into shape.
func handoffSetField(k handoffKind, entry *handoffEntry, field, value string) error {
	fail := func(reason string) error { return fmt.Errorf("--%s %s", field, reason) }
	number := func(pattern *regexp.Regexp, what string) (int64, error) {
		if !pattern.MatchString(value) {
			return 0, fail("is not " + what)
		}
		return strconv.ParseInt(value, 10, 64)
	}
	listed := func(list []string) error {
		if !handoffIn(value, list) {
			return fail("is not one of: " + strings.Join(list, ", "))
		}
		return nil
	}
	const message = "a Board message number (1 to 12 digits)"
	var err error
	switch field {
	case "message":
		entry.Message, err = number(handoffMessagePattern, message)
	case "order":
		entry.Order, err = number(handoffMessagePattern, message)
	case "check":
		entry.Check, err = number(handoffMessagePattern, message)
	case "revision":
		entry.Revision, err = number(handoffRevisionPattern, "a revision number (1 to 9 digits)")
	case "item":
		if !api.ValidID(value, "wi") {
			return fail("is not a work-item id (wi_ and 16 hex digits)")
		}
		entry.Item = value
	case "schedule":
		if entry.Schedule, err = handoffParseSchedule(value); err != nil {
			return fail(err.Error())
		}
	case "kind":
		if err = listed(handoffWakeKinds); err == nil {
			entry.Kind = value
		}
	case "by":
		if err = listed(handoffGivers); err == nil {
			entry.By = value
		}
	case "authority":
		if err = listed(handoffAuthorities); err == nil {
			entry.By = value
		}
	case "last":
		if err = listed(handoffOrderSteps); err == nil {
			entry.Last = value
		}
	case "next":
		if err = listed(handoffOrderSteps); err == nil {
			entry.Next = value
		}
	case "given":
		if entry.Given, err = handoffParseTime(value); err != nil {
			return fail(err.Error())
		}
	case "expires":
		if entry.Expires, err = handoffParseExpiry(value); err != nil {
			return fail(err.Error())
		}
	default:
		return fmt.Errorf("a %s note has no --%s", k.name, field)
	}
	return err
}

// handoffEntryState is the state shown for an entry at now: an active entry
// past its expiry is expired without anything having run.
func handoffEntryState(entry handoffEntry, now time.Time) string {
	if entry.State == "active" && entry.Expires != "" && entry.Expires != handoffNone {
		if t, err := time.Parse(handoffTimeLayout, entry.Expires); err == nil && !now.Before(t) {
			return "expired"
		}
	}
	return entry.State
}

// handoffLive reports a state that still asks something of the session.
func handoffLive(state string) bool {
	return state == "active" || state == "open" || state == "unverified" || state == "recorded"
}

// valid reports whether every value in the record is one tt could have
// written. A record that fails is never printed or injected: a hand-edited
// file must not put words into a session's context.
func (r handoffRecord) valid() bool {
	id := r.Identity
	if r.V != 1 || !handoffHubPattern.MatchString(id.Hub) || !api.ValidID(id.Task, "tsk") || !api.ValidID(id.Agent, "agt") || !handoffTimeOK(id.CopiedAt) ||
		!handoffID(id.Run, "run") || id.Name != "" && !api.ValidName(id.Name) || id.Registration != "" && !handoffID(id.Registration, "ohr") ||
		id.Runtime != "" && !handoffIn(id.Runtime, handoffRuntimes) || id.Thread != "" && !threadIDPattern.MatchString(id.Thread) ||
		id.Session != "" && !api.ValidName(id.Session) || id.SessionID != "" && !sessionIDPattern.MatchString(id.SessionID) || len(id.SessionID) > 12 ||
		id.SessionCreated != "" && !sessionTimePattern.MatchString(id.SessionCreated) || len(id.SessionCreated) > 12 {
		return false
	}
	for _, c := range []struct {
		stamp *handoffStamp
		list  []string
	}{{r.Capture.Start, handoffStartSources}, {r.Capture.Compact, handoffTriggers}, {r.Capture.End, handoffEndReasons}} {
		if s := c.stamp; s != nil && (!handoffTimeOK(s.Time) || s.Detail != handoffOther && !handoffIn(s.Detail, c.list) || s.Session != "" && !threadIDPattern.MatchString(s.Session)) {
			return false
		}
	}
	if s := r.Snapshot; s != nil {
		if !handoffTimeOK(s.AsOf) || s.HelperStatus != handoffOther && !handoffIn(s.HelperStatus, handoffAgentStatuses) ||
			len(s.Obligations) > handoffListCap || len(s.Decisions) > handoffListCap || len(s.Queue) > handoffListCap ||
			s.ObligationsOmitted < 0 || s.DecisionsOmitted < 0 || s.QueueOmitted < 0 {
			return false
		}
		if w := s.Window; w != nil && (!handoffID(w.ID, "dlw") || !handoffIn(w.Scope, append([]string{handoffOther}, handoffWindowScopes...)) || !handoffTimeOK(w.EndsAt) || !handoffIn(w.State, handoffWindowStates)) {
			return false
		}
		sender := func(s string) bool { return api.ValidID(s, "agt") || handoffIn(s, handoffSenderWords) }
		for _, o := range s.Obligations {
			if !handoffID(o.ID, "obl") || o.Message < 1 || !handoffIn(o.Kind, append([]string{handoffOther}, handoffObligKinds...)) || !sender(o.Sender) ||
				o.DueAt != "" && !handoffTimeOK(o.DueAt) || !handoffIn(o.State, append([]string{handoffOther}, handoffObligStates...)) {
				return false
			}
		}
		for _, d := range s.Decisions {
			if d.Message < 1 || !sender(d.Sender) || d.State != "open" {
				return false
			}
		}
		for _, q := range s.Queue {
			if !handoffID(q.ID, "tqe") || !api.ValidID(q.Item, "wi") || q.Revision < 1 || q.Order < 0 || !handoffIn(q.State, handoffQueueStates) {
				return false
			}
		}
	}
	for _, k := range handoffKinds {
		list := k.list(&r.Notes)
		if len(list.Entries) > handoffListCap || list.Next < 0 || list.Dropped < 0 || list.Changed != "" && !handoffTimeOK(list.Changed) {
			return false
		}
		for _, entry := range list.Entries {
			if !handoffEntryValid(k, entry) {
				return false
			}
		}
	}
	return true
}

func handoffEntryValid(k handoffKind, e handoffEntry) bool {
	if !handoffEntryIDPattern.MatchString(e.ID) || !strings.HasPrefix(e.ID, k.prefix) || !handoffTimeOK(e.Created) || !handoffTimeOK(e.Updated) ||
		e.State != k.open && !handoffIn(e.State, k.closed) || e.Message < 0 || e.Order < 0 || e.Check < 0 || e.Revision < 0 {
		return false
	}
	// Every field the kind does not use must be empty, and every one it uses
	// must hold a validated value.
	want := handoffEntry{ID: e.ID, State: e.State, Created: e.Created, Updated: e.Updated, Message: e.Message}
	uses := func(field string) bool { return handoffIn(field, k.fields) }
	if uses("schedule") {
		if s, err := handoffParseSchedule(e.Schedule); err != nil || s != e.Schedule || !handoffIn(e.Kind, handoffWakeKinds) {
			return false
		}
		want.Schedule, want.Kind = e.Schedule, e.Kind
		switch e.Receipt {
		case "":
		case handoffRestored:
			if !handoffToolUsePattern.MatchString(e.ReceiptTool) {
				return false
			}
			want.ReceiptTool = e.ReceiptTool
			fallthrough
		case handoffAsserted:
			if !threadIDPattern.MatchString(e.ReceiptSession) || !handoffTimeOK(e.ReceiptAt) {
				return false
			}
			want.Receipt, want.ReceiptSession, want.ReceiptAt = e.Receipt, e.ReceiptSession, e.ReceiptAt
		default:
			return false
		}
		if e.Fired != "" && !handoffTimeOK(e.Fired) || e.Duplicates < 0 {
			return false
		}
		want.Fired, want.Duplicates = e.Fired, e.Duplicates
	}
	if uses("expires") {
		if e.Expires != handoffNone && !handoffTimeOK(e.Expires) {
			return false
		}
		want.Expires = e.Expires
	}
	if uses("by") && !handoffIn(e.By, handoffGivers) || uses("authority") && !handoffIn(e.By, handoffAuthorities) {
		return false
	}
	if uses("by") || uses("authority") {
		want.By = e.By
	}
	if uses("given") {
		if !handoffTimeOK(e.Given) {
			return false
		}
		want.Given = e.Given
	}
	if uses("item") {
		if !api.ValidID(e.Item, "wi") || e.Revision < 1 || e.Order < 1 || !handoffIn(e.Last, handoffOrderSteps) || !handoffIn(e.Next, handoffOrderSteps) {
			return false
		}
		want.Item, want.Revision, want.Order, want.Last, want.Next = e.Item, e.Revision, e.Order, e.Last, e.Next
	} else if e.Message < 1 {
		return false
	}
	if k.checkOnClose {
		want.Check = e.Check
	}
	return e == want
}

