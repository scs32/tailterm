// handoffRoute is the command dispatch for tt handoff: the handler for the
// words that follow, and how many of them it consumed.
func handoffRoute(args []string) (func(e env, args []string) error, int) {
	if len(args) == 0 {
		return nil, 0
	}
	switch args[0] {
	case "show":
		return handoffShowCommand, 1
	case "write":
		return handoffWriteCommand, 1
	case "note":
		if len(args) < 3 {
			return nil, 0
		}
		k, ok := handoffKindNamed(args[1])
		if !ok || args[2] != "add" && args[2] != "set" && args[2] != "close" {
			return nil, 0
		}
		action := args[2]
		return func(e env, rest []string) error { return handoffNoteCommand(e, k, action, rest) }, 3
	}
	return nil, 0
}

func cmdHandoff(e env, args []string) error {
	run, used := handoffRoute(args)
	if run == nil {
		return errors.New(handoffUsage)
	}
	return run(e, args[used:])
}

func handoffFlags(name string) *flag.FlagSet {
	fs := flag.NewFlagSet(name, flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	return fs
}

// handoffHelperFor finds the helper file a command acts on: the project's
// when --task names one, otherwise the one registered from this runtime
// session. It asks no hub.
func handoffHelperFor(e env, task string) (ownerHelperFile, error) {
	files, _ := handoffHelperFiles()
	runtime, thread, single := sessionHelperThread()
	if task == "" {
		if f, ok := handoffMatchThread(files, runtime, thread); ok && single {
			return f, nil
		}
		return ownerHelperFile{}, errors.New("this session is not a registered owner helper on this host; name the project with --task")
	}
	if !api.ValidID(task, "tsk") {
		return ownerHelperFile{}, errors.New("--task is not a project id")
	}
	var found []ownerHelperFile
	for _, f := range files {
		if f.Task == task && (e.hub == "" || f.Hub == e.hub) {
			found = append(found, f)
		}
	}
	if len(found) != 1 {
		return ownerHelperFile{}, errors.New("no owner helper is registered on this host for this project; run tt helper register")
	}
	return found[0], nil
}

// handoffWriter is the helper a command may write notes for. A runtime
// session other than the registered one is refused, and so is an agent
// identity that is not the helper's. A shell with no runtime session is the
// owner typing by hand and is allowed.
func handoffWriter(e env, task string) (ownerHelperFile, error) {
	helper, err := handoffHelperFor(e, task)
	if err != nil {
		return ownerHelperFile{}, err
	}
	runtime, thread, single := sessionHelperThread()
	both := !single && os.Getenv("CODEX_THREAD_ID") != ""
	if both || single && (runtime != helper.Runtime || thread != helper.Thread) || e.agent != "" && e.agent != helper.Agent {
		return ownerHelperFile{}, errors.New("this session is not the registered owner helper; run tt helper register first")
	}
	return helper, nil
}

func handoffNoteCommand(e env, k handoffKind, action string, args []string) error {
	if !handoffOn() {
		return handoffOffError()
	}
	id := ""
	if action != "add" {
		if len(args) == 0 || !handoffEntryIDPattern.MatchString(args[0]) || !strings.HasPrefix(args[0], k.prefix) {
			return fmt.Errorf("name the %s by its id, such as %s1", k.name, k.prefix)
		}
		id, args = args[0], args[1:]
	}
	fs := handoffFlags("handoff note")
	task := fs.String("task", e.task, "project id")
	fields := append([]string{}, k.fields...)
	if action == "close" {
		fields = []string{"state"}
		if k.checkOnClose {
			fields = append(fields, "check")
		}
	}
	values := map[string]*string{}
	for _, field := range fields {
		values[field] = fs.String(field, "", "")
	}
	if err := fs.Parse(args); err != nil || fs.NArg() > 0 {
		return errors.New(handoffUsage)
	}
	given := map[string]bool{}
	fs.Visit(func(f *flag.Flag) { given[f.Name] = true })
	helper, err := handoffWriter(e, *task)
	if err != nil {
		return err
	}
	store, ok := handoffStoreFor(helper.Agent, handoffCommandLockWait)
	if !ok {
		return errors.New("no handoff state directory")
	}
	now := handoffNow()
	stamp := handoffStamped(now)
	// The entry is built and validated in full before the directory, the lock
	// or the record is touched, so a refused value changes nothing.
	change := handoffEntry{}
	for _, field := range fields {
		if !given[field] || field == "state" {
			continue
		}
		if err := handoffSetField(k, &change, field, *values[field]); err != nil {
			return err
		}
	}
	state := ""
	switch action {
	case "add":
		for _, field := range k.required {
			if !given[field] {
				return fmt.Errorf("a %s note needs --%s", k.name, field)
			}
		}
	case "close":
		state = k.closed[0]
		if given["state"] {
			state = *values["state"]
		} else if len(k.closed) > 1 && k.checkOnClose {
			return fmt.Errorf("closing a %s needs --state %s", k.name, strings.Join(k.closed, "|"))
		}
		if !handoffIn(state, k.closed) {
			return fmt.Errorf("--state is not one of: %s", strings.Join(k.closed, ", "))
		}
		if k.checkOnClose && !given["check"] {
			return fmt.Errorf("closing a %s needs --check with the Board message number of the check", k.name)
		}
	default:
		if len(given) == 0 || len(given) == 1 && given["task"] {
			return errors.New("nothing to set")
		}
	}
	if err := store.prepare(); err != nil {
		return err
	}
	unlock := store.lock()
	if unlock == nil {
		return errors.New("the handoff record is locked by another command; try again")
	}
	defer unlock()
	r, previous, err := store.load()
	if errors.Is(err, errHandoffNoRecord) {
		r, err = handoffRecord{V: 1}, nil
	}
	if err != nil {
		return err
	}
	r.refreshIdentity(helper)
	list := k.list(&r.Notes)
	var entry handoffEntry
	if action == "add" {
		if len(list.Entries) >= handoffListCap {
			// Make room by dropping the oldest entry that is no longer
			// current. Current entries are never dropped.
			oldest := -1
			for i, e := range list.Entries {
				if !handoffLive(handoffEntryState(e, now)) {
					oldest = i
					break
				}
			}
			if oldest < 0 {
				return fmt.Errorf("the %s list is full (%d current entries); close one first", k.plural, handoffListCap)
			}
			list.Entries = append(list.Entries[:oldest:oldest], list.Entries[oldest+1:]...)
			list.Dropped++
		}
		list.Next = max(list.Next, 1)
		entry = change
		entry.ID, entry.State, entry.Created, entry.Updated = k.prefix+strconv.Itoa(list.Next), k.open, stamp, stamp
		if handoffIn("expires", k.fields) && entry.Expires == "" {
			entry.Expires = handoffNone
		}
		if handoffIn("given", k.fields) && entry.Given == "" {
			entry.Given = stamp
		}
		list.Next++
		list.Entries = append(list.Entries, entry)
	} else {
		at := -1
		for i, e := range list.Entries {
			if e.ID == id {
				at = i
			}
		}
		if at < 0 {
			return fmt.Errorf("no %s %s in the record", k.name, id)
		}
		entry = list.Entries[at]
		for _, field := range fields {
			if given[field] && field != "state" {
				_ = handoffSetField(k, &entry, field, *values[field]) // validated above
			}
		}
		if action == "close" {
			entry.State = state
		}
		entry.Updated = stamp
		list.Entries[at] = entry
	}
	list.Changed = stamp
	if err := store.save(r, previous); err != nil {
		return err
	}
	fmt.Println(handoffEntryLine(k, entry, now))
	return nil
}

func handoffShowCommand(e env, args []string) error {
	fs := handoffFlags("handoff show")
	task := fs.String("task", e.task, "project id")
	asJSON := fs.Bool("json", false, "print the record as JSON")
	if err := fs.Parse(args); err != nil || fs.NArg() > 0 {
		return errors.New(handoffUsage)
	}
	agent, err := handoffShowAgent(e, *task)
	if err != nil {
		return err
	}
	store, ok := handoffStoreFor(agent, handoffCommandLockWait)
	if !ok {
		return errors.New("no handoff state directory")
	}
	r, _, err := store.load()
	if errors.Is(err, errHandoffNoRecord) {
		return fmt.Errorf("no handoff record for %s on this host", agent)
	}
	if err != nil {
		return err
	}
	now := handoffNow()
	if *asJSON {
		// The stored states, with expiry applied as of now, as the text shows.
		for _, k := range handoffKinds {
			list := k.list(&r.Notes)
			for i := range list.Entries {
				list.Entries[i].State = handoffEntryState(list.Entries[i], now)
			}
		}
		printJSON(r)
		return nil
	}
	fmt.Print(handoffShow(r, now))
	if !handoffOn() {
		fmt.Printf("\nSession handoff is off on this host (%s). The record is kept and shown; nothing updates it.\n", handoffConfigPath())
	}
	return nil
}

// handoffShowAgent finds whose record to show without the hub: the named
// project's helper, the helper registered from this session, the helper
// whose tmux session this is, or the only record on the host.
func handoffShowAgent(e env, task string) (string, error) {
	if helper, err := handoffHelperFor(e, task); err == nil {
		return helper.Agent, nil
	} else if task != "" {
		return "", err
	}
	files, _ := handoffHelperFiles()
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()
	if helper, ok := handoffMatchTmux(ctx, files); ok {
		return helper.Agent, nil
	}
	root := handoffRoot()
	handoffTouch(root)
	entries, _ := os.ReadDir(root)
	var agents []string
	for _, entry := range entries {
		if entry.IsDir() && api.ValidID(entry.Name(), "agt") {
			agents = append(agents, entry.Name())
		}
	}
	if len(agents) == 1 {
		return agents[0], nil
	}
	return "", errors.New("cannot tell which handoff record this session means; name the project with --task")
}

// handoffWriteCommand reads the hub for the snapshot and rewrites the record.
// It reads the helper agent, its delegation windows, the obligations it owes
// (and, for who sent each, its one Board message), the open owner decisions
// and the team queue. It reads no work-item record
// and changes nothing on the hub: the obligations are listed without a run,
// so none is marked delivered.
func handoffWriteCommand(e env, args []string) error {
	fs := handoffFlags("handoff write")
	task := fs.String("task", e.task, "project id")
	out := fs.String("out", "", "also render the record to this file")
	if err := fs.Parse(args); err != nil || fs.NArg() > 0 {
		return errors.New(handoffUsage)
	}
	if !handoffOn() {
		return handoffOffError()
	}
	if *task == "" {
		return errors.New(handoffUsage)
	}
	helper, err := handoffWriter(e, *task)
	if err != nil {
		return err
	}
	if e.hub == "" {
		e.hub = helper.Hub
	}
	if e.hub != helper.Hub {
		return errors.New("the owner helper on this host is registered with another hub")
	}
	snapshot, err := handoffReadHub(e, helper)
	if err != nil {
		return err
	}
	store, ok := handoffStoreFor(helper.Agent, handoffCommandLockWait)
	if !ok {
		return errors.New("no handoff state directory")
	}
	if err := store.prepare(); err != nil {
		return err
	}
	unlock := store.lock()
	if unlock == nil {
		return errors.New("the handoff record is locked by another command; try again")
	}
	defer unlock()
	r, previous, err := store.load()
	if errors.Is(err, errHandoffNoRecord) {
		r, err = handoffRecord{V: 1}, nil
	}
	if err != nil {
		return err
	}
	r.refreshIdentity(helper)
	r.Snapshot = &snapshot
	if err := store.save(r, previous); err != nil {
		return err
	}
	path := store.path("record.json")
	size := int64(0)
	if info, err := os.Stat(path); err == nil {
		size = info.Size()
	}
	fmt.Printf("handoff record written: %s (%d bytes), hub snapshot as of %s\n", path, size, snapshot.AsOf)
	destination := fmt.Sprintf("In the destination session, in its own one-pane tmux session:\n  tt helper register --task %[1]s\n  tt handoff show --task %[1]s\n  tt handoff note wake add ...   (after re-creating each active wake by hand)\n", helper.Task)
	if *out != "" {
		text := handoffShow(r, handoffNow()) + "\n## For the destination session\n\n" + destination +
			"Registration and wakes are not restored automatically in this version. This file is a copy; the record and the hub are the sources.\n"
		handoffTouch(*out)
		if err := os.WriteFile(*out, []byte(text), 0600); err != nil {
			return err
		}
		fmt.Printf("rendered: %s\n", *out)
	}
	fmt.Print(destination)
	return nil
}

func handoffReadHub(e env, helper ownerHelperFile) (handoffSnapshot, error) {
	c, err := e.client(10 * time.Second)
	if err != nil {
		return handoffSnapshot{}, err
	}
	ctx, cancel := ctxTimeout(30 * time.Second)
	defer cancel()
	a, err := c.GetAgent(ctx, helper.Task, helper.Agent)
	if err != nil {
		return handoffSnapshot{}, err
	}
	if a.Role != api.AgentRoleOwnerHelper || a.RunID != helper.Run {
		return handoffSnapshot{}, errors.New("the owner helper was registered again elsewhere; run tt helper register here first")
	}
	now := handoffNow()
	s := handoffSnapshot{AsOf: handoffStamped(now), HelperStatus: handoffListed(a.Status, handoffAgentStatuses),
		Obligations: []handoffObligation{}, Decisions: []handoffDecision{}, Queue: []handoffQueueRow{}}
	sender := func(from api.Sender) string {
		switch {
		case api.ValidID(from.AgentID, "agt"):
			return from.AgentID
		case from.AgentID == "" && from.User != "":
			return "human"
		}
		return "unknown"
	}
	windows, err := c.ListDelegationWindows(ctx, helper.Task)
	if err != nil {
		return handoffSnapshot{}, err
	}
	// The helper's newest window: an open one if there is one.
	var window *api.DelegationWindow
	for i, w := range windows.Windows {
		if w.DelegateAgentID != helper.Agent || !handoffID(w.ID, "dlw") {
			continue
		}
		if window == nil || w.Active(now) && !window.Active(now) || w.Active(now) == window.Active(now) && w.CreatedAt.After(window.CreatedAt) {
			window = &windows.Windows[i]
		}
	}
	if window != nil {
		state := handoffListed(window.State, handoffWindowStates)
		if state == handoffOther || state == api.DelegationOpen && !now.Before(window.EndsAt) {
			state = api.DelegationExpired
		}
		s.Window = &handoffWindow{ID: window.ID, Scope: handoffListed(window.Scope, handoffWindowScopes), EndsAt: handoffStamped(window.EndsAt), State: state}
	}
	obligations, err := c.ListObligations(ctx, helper.Task, helper.Agent, "", true, false)
	if err != nil {
		return handoffSnapshot{}, err
	}
	for _, o := range obligations {
		if o.AgentID != helper.Agent || !handoffID(o.ID, "obl") || o.MessageSeq < 1 {
			continue
		}
		if len(s.Obligations) == handoffListCap {
			s.ObligationsOmitted++
			continue
		}
		row := handoffObligation{ID: o.ID, Message: o.MessageSeq, Kind: handoffListed(o.SourceKind, handoffObligKinds), Sender: "unknown", State: handoffListed(o.State, handoffObligStates)}
		if o.Request != nil {
			row.Sender = sender(o.Request.From)
		} else if page, err := c.ListMessages(ctx, helper.Task, o.MessageSeq-1, "", 1); err == nil && len(page) == 1 && page[0].Seq == o.MessageSeq {
			// The listing carries the request only for the owner's own
			// obligations; read the one message for who sent it. Its text
			// is not kept.
			row.Sender = sender(page[0].From)
		}
		if !o.DueAt.IsZero() {
			row.DueAt = handoffStamped(o.DueAt)
		}
		s.Obligations = append(s.Obligations, row)
	}
	for after, pages := int64(0), 0; pages < 200; pages++ {
		page, err := c.ListDecisions(ctx, helper.Task, after, api.MaxDecisionPage)
		if err != nil {
			return handoffSnapshot{}, err
		}
		for _, d := range page.Decisions {
			if d.Answer != nil || d.Request.Seq < 1 {
				continue
			}
			if len(s.Decisions) == handoffListCap {
				s.DecisionsOmitted++
				continue
			}
			s.Decisions = append(s.Decisions, handoffDecision{Message: d.Request.Seq, Sender: sender(d.Request.From), State: "open"})
		}
		if page.NextAfter <= after {
			break
		}
		after = page.NextAfter
	}
	queue, err := c.ListTeamQueuePage(ctx, helper.Task, api.TeamQueueListOptions{View: api.TeamQueueViewActive})
	if err != nil {
		return handoffSnapshot{}, err
	}
	for _, q := range queue.Entries {
		if !handoffIn(q.State, handoffQueueStates) || !handoffID(q.ID, "tqe") || !api.ValidID(q.ItemID, "wi") || q.ItemRevision < 1 {
			continue
		}
		if len(s.Queue) == handoffListCap {
			s.QueueOmitted++
			continue
		}
		s.Queue = append(s.Queue, handoffQueueRow{ID: q.ID, Item: q.ItemID, Revision: q.ItemRevision, Order: q.OrderMessageSeq, State: q.State})
	}
	return s, nil
}
