// handoffHelperFiles reads the host's owner helper files, without the hub.
// It trusts a file only under the name its own hub and task give it and
// gives up past the same bounds as offlineOwnerHelper.
func handoffHelperFiles() ([]ownerHelperFile, bool) {
	dir := relayDir()
	handoffTouch(dir)
	d, err := os.Open(dir)
	if err != nil {
		return nil, false
	}
	defer d.Close()
	var candidates []string
	for {
		names, err := d.Readdirnames(4096) // names only: no stat per entry
		for _, name := range names {
			if !strings.HasSuffix(name, ownerHelperSuffix) {
				continue
			}
			if len(candidates) == ownerHelperCandidates {
				return nil, false
			}
			candidates = append(candidates, name)
		}
		if err != nil {
			if err != io.EOF {
				return nil, false
			}
			break
		}
	}
	sort.Strings(candidates)
	var files []ownerHelperFile
	for _, name := range candidates {
		var f ownerHelperFile
		path := filepath.Join(dir, name)
		handoffTouch(path)
		if readOwnerHelperFile(path, &f) != nil {
			continue
		}
		if name != filepath.Base(ownerHelperPath(f.Hub, f.Task)) || !handoffIdentityOf(f, time.Time{}).usable() {
			continue
		}
		files = append(files, f)
	}
	return files, true
}

// handoffIdentityOf copies the identity fields of a helper file. Its request
// ids and hashes are not copied.
func handoffIdentityOf(f ownerHelperFile, at time.Time) handoffIdentity {
	return handoffIdentity{Hub: f.Hub, Task: f.Task, Agent: f.Agent, Name: f.Name, Run: f.Run, Registration: f.Registration, Runtime: f.Runtime,
		Thread: f.Thread, Session: f.Session, SessionID: f.SessionID, SessionCreated: f.SessionCreated, CopiedAt: handoffStamped(at)}
}

// usable reports a helper file whose identity the record can hold.
func (id handoffIdentity) usable() bool {
	return handoffRecord{V: 1, Identity: id}.valid() && toolLedgerAgentOK(id.Agent)
}

// same compares two identities apart from when they were copied.
func (id handoffIdentity) same(other handoffIdentity) bool {
	other.CopiedAt = id.CopiedAt
	return id == other
}

// handoffMatchThread is the one helper file naming this runtime thread.
func handoffMatchThread(files []ownerHelperFile, runtime, thread string) (ownerHelperFile, bool) {
	var found ownerHelperFile
	matches := 0
	if runtime == "" || !threadIDPattern.MatchString(thread) {
		return found, false
	}
	for _, f := range files {
		if f.Runtime == runtime && f.Thread == thread {
			found = f
			matches++
		}
	}
	return found, matches == 1
}

// handoffMatchTmux is the one helper file whose tmux session, by id and
// creation time, is the session this process's pane is in. It asks tmux at
// most once, and not at all when no helper file names a tmux session.
func handoffMatchTmux(ctx context.Context, files []ownerHelperFile) (ownerHelperFile, bool) {
	pane := os.Getenv("TMUX_PANE")
	named := false
	for _, f := range files {
		named = named || f.SessionID != "" && f.SessionCreated != ""
	}
	if !named || os.Getenv("TMUX") == "" || pane == "" {
		return ownerHelperFile{}, false
	}
	args := []string{"display-message", "-p", "-t", pane, "-F", `["#{q/e:session_id}","#{q/e:session_created}"]`}
	if socket := os.Getenv("TT_TMUX_SOCKET"); socket != "" {
		args = append([]string{"-L", socket}, args...)
	}
	cmd := exec.CommandContext(ctx, "tmux", args...)
	cmd.WaitDelay = 20 * time.Millisecond
	raw, err := cmd.Output()
	var values []string
	if err != nil || json.Unmarshal(bytes.TrimSpace(raw), &values) != nil || len(values) != 2 ||
		!sessionIDPattern.MatchString(values[0]) || !sessionTimePattern.MatchString(values[1]) {
		return ownerHelperFile{}, false
	}
	var found ownerHelperFile
	matches := 0
	for _, f := range files {
		if f.SessionID == values[0] && f.SessionCreated == values[1] {
			found = f
			matches++
		}
	}
	return found, matches == 1
}

// ---- the hook ----

// handoffHookInput holds the only fields decoded from Claude Code's payload.
// cwd, transcript_path and custom_instructions are skipped by the decoder.
type handoffHookInput struct {
	Event   string `json:"hook_event_name"`
	Session string `json:"session_id"`
	Source  string `json:"source"`
	Trigger string `json:"trigger"`
	Reason  string `json:"reason"`
}

// handoffHook runs for SessionStart, PreCompact and SessionEnd. It checks the
// setting first and returns at once when it is off or when the session is a
// Tailterm agent. Otherwise the work, stdin read included, happens in a
// goroutine the handler waits on for at most the deadline. When the handler
// returns, cmdHook returns nil and the process exits 0.
//
// It makes no hub request. Only SessionStart ever prints, and only for the
// helper's own session or a new session in the helper's tmux session.
func handoffHook(e env, _ []string) {
	if !handoffOn() || e.agent != "" {
		return
	}
	run := handoffHookRun{started: time.Now(), deadline: handoffDeadline, in: os.Stdin, out: os.Stdout}
	done := make(chan struct{})
	go func() {
		defer close(done)
		defer func() { _ = recover() }()
		run.work()
	}()
	timer := time.NewTimer(run.deadline)
	defer timer.Stop()
	select {
	case <-done:
	case <-timer.C:
		run.mu.Lock()
		if run.owes {
			_, _ = io.WriteString(run.out, handoffLateLine)
		}
		run.closed = true
		run.mu.Unlock()
	}
}

type handoffHookRun struct {
	started  time.Time
	deadline time.Duration
	in       io.Reader
	out      io.Writer
	mu       sync.Mutex
	owes     bool // a matched SessionStart has not printed yet
	closed   bool // the handler has returned; print nothing more
}

func (h *handoffHookRun) late() bool { return time.Since(h.started) >= h.deadline }

func (h *handoffHookRun) work() {
	data, err := io.ReadAll(io.LimitReader(h.in, handoffMaxInput+1))
	var p handoffHookInput
	if err != nil || h.late() || len(data) > handoffMaxInput || json.Unmarshal(data, &p) != nil {
		return
	}
	var slot func(*handoffCapture) **handoffStamp
	stamp := handoffStamp{Time: handoffStamped(handoffNow())}
	switch p.Event {
	case "SessionStart":
		stamp.Detail, slot = handoffListed(p.Source, handoffStartSources), func(c *handoffCapture) **handoffStamp { return &c.Start }
	case "PreCompact":
		stamp.Detail, slot = handoffListed(p.Trigger, handoffTriggers), func(c *handoffCapture) **handoffStamp { return &c.Compact }
	case "SessionEnd":
		stamp.Detail, slot = handoffListed(p.Reason, handoffEndReasons), func(c *handoffCapture) **handoffStamp { return &c.End }
	default:
		return
	}
	thread := p.Session
	if !threadIDPattern.MatchString(thread) {
		thread = os.Getenv("CLAUDE_CODE_SESSION_ID")
	}
	if threadIDPattern.MatchString(thread) {
		stamp.Session = strings.ToLower(thread)
	}
	files, ok := handoffHelperFiles()
	if !ok || len(files) == 0 {
		return
	}
	ctx, cancel := context.WithDeadline(context.Background(), h.started.Add(h.deadline))
	defer cancel()
	helper, match := ownerHelperFile{}, handoffAsRegistered
	if found, ok := handoffMatchThread(files, "claude", thread); ok {
		helper = found
	} else if found, ok := handoffMatchTmux(ctx, files); ok {
		helper, match = found, handoffAsCandidate
	} else {
		return
	}
	start := p.Event == "SessionStart"
	if start {
		h.mu.Lock()
		h.owes = !h.closed
		h.mu.Unlock()
	}
	if h.late() {
		return
	}
	note := handoffBrokenLine
	if store, ok := handoffStoreFor(helper.Agent, handoffHookLockWait); ok {
		if r, noEnd, err := store.stamp(helper, p.Event, stamp, slot, match, h.late); err == nil {
			note = handoffNote(r, match, noEnd, handoffNow())
		}
	}
	if !start {
		return
	}
	h.mu.Lock()
	if !h.closed {
		_, _ = io.WriteString(h.out, note)
	}
	h.owes = false
	h.mu.Unlock()
}

// stamp records one hook event in the record's capture part and the capture
// log, leaving the notes and the snapshot as they were. It returns the record
// and whether the previous session left no end stamp. A record that cannot
// be written is still returned, so the note is printed from what was read.
func (s handoffStore) stamp(helper ownerHelperFile, event string, stamp handoffStamp, slot func(*handoffCapture) **handoffStamp, match string, late func() bool) (handoffRecord, bool, error) {
	prepared := s.prepare() == nil
	var unlock func()
	if prepared {
		unlock = s.lock()
	}
	if unlock != nil {
		defer unlock()
	}
	r, previous, err := s.load()
	if errors.Is(err, errHandoffNoRecord) {
		r, err = handoffRecord{V: 1}, nil
	}
	if err != nil {
		return handoffRecord{}, false, err
	}
	// A start that follows a start with no end between them means the
	// previous session was killed; a compaction continues the same session.
	noEnd := event == "SessionStart" && stamp.Detail != "compact" && r.Capture.Start != nil &&
		(r.Capture.End == nil || r.Capture.End.Time < r.Capture.Start.Time)
	r.refreshIdentity(helper)
	*slot(&r.Capture) = &stamp
	if unlock == nil || late() {
		return r, noEnd, nil
	}
	if s.save(r, previous) == nil {
		s.appendCapture(event, stamp, match)
	}
	return r, noEnd, nil
}

// refreshIdentity copies the helper file's identity when it differs from the
// record's, and leaves the copy time alone when it does not.
func (r *handoffRecord) refreshIdentity(helper ownerHelperFile) {
	if id := handoffIdentityOf(helper, handoffNow()); !r.Identity.same(id) {
		r.Identity = id
	}
}

// ---- the injected note and tt handoff show ----

// handoffEntryLine is one entry in full, for tt handoff show. It holds ids,
// states, Board message numbers, times and fixed-list values: no words from
// any message.
func handoffEntryLine(k handoffKind, e handoffEntry, now time.Time) string {
	line := fmt.Sprintf("%s %s %s", e.ID, handoffEntryState(e, now), k.name)
	switch k.name {
	case "wake":
		line += fmt.Sprintf(" %s cron %q msg #%d expires %s", e.Kind, e.Schedule, e.Message, e.Expires)
	case "instruction":
		line += fmt.Sprintf(" msg #%d by %s given %s expires %s", e.Message, e.By, e.Given, e.Expires)
	case "order":
		line += fmt.Sprintf(" %s rev %d order #%d last %s next %s", e.Item, e.Revision, e.Order, e.Last, e.Next)
		if e.Message > 0 {
			line += fmt.Sprintf(" msg #%d", e.Message)
		}
	case "decision":
		line += fmt.Sprintf(" msg #%d authority %s", e.Message, e.By)
	case "claim":
		line += fmt.Sprintf(" msg #%d", e.Message)
		if e.Check > 0 {
			line += fmt.Sprintf(" check #%d", e.Check)
		}
	}
	return line
}

// handoffBriefLine is one entry on one line of at most handoffLineBytes, for
// the injected note: the entry id, its state, its kind, its Board message
// number and its expiry. A wake's schedule is added only when it fits; the
// rest of an entry is in tt handoff show.
func handoffBriefLine(k handoffKind, e handoffEntry, now time.Time) string {
	line := fmt.Sprintf("%s %s %s", e.ID, handoffEntryState(e, now), k.name)
	switch k.name {
	case "wake":
		line += fmt.Sprintf(" %s msg #%d expires %s", e.Kind, e.Message, e.Expires)
		if cron := fmt.Sprintf(" cron %q", e.Schedule); len(line)+len(cron) <= handoffLineBytes {
			line += cron
		}
	case "instruction":
		line += fmt.Sprintf(" msg #%d by %s expires %s", e.Message, e.By, e.Expires)
	case "order":
		line += fmt.Sprintf(" %s rev %d order #%d next %s", e.Item, e.Revision, e.Order, e.Next)
	case "decision":
		line += fmt.Sprintf(" msg #%d authority %s", e.Message, e.By)
	case "claim":
		line += fmt.Sprintf(" msg #%d", e.Message)
		if e.Check > 0 {
			line += fmt.Sprintf(" check #%d", e.Check)
		}
	}
	return line
}

// handoffNoteLine is a body line and the note list it counts against when it
// is left out; headings and the snapshot lines count against none.
type handoffNoteLine struct {
	text, list string
}

// handoffBody is the note's body in its fixed order: active instructions,
// active wakes, open orders, the snapshot's counts, unverified claims,
// recorded decisions, then everything expired, revoked, cancelled or closed.
func handoffBody(r handoffRecord, now time.Time) []handoffNoteLine {
	var lines []handoffNoteLine
	group := func(heading string, k handoffKind, keep func(state string) bool) {
		first := true
		for _, e := range k.list(&r.Notes).Entries {
			if !keep(handoffEntryState(e, now)) {
				continue
			}
			if first {
				lines, first = append(lines, handoffNoteLine{heading, ""}), false
			}
			lines = append(lines, handoffNoteLine{handoffBriefLine(k, e, now), k.plural})
		}
	}
	kind := func(name string) handoffKind { k, _ := handoffKindNamed(name); return k }
	group("Active instructions:", kind("instruction"), handoffLive)
	group("Active wakes:", kind("wake"), handoffLive)
	group("Open orders:", kind("order"), handoffLive)
	if s := r.Snapshot; s != nil {
		lines = append(lines,
			handoffNoteLine{fmt.Sprintf("Hub snapshot as of %s (read the hub again before acting): helper %s", s.AsOf, s.HelperStatus), ""},
			handoffNoteLine{fmt.Sprintf("%d obligations, %d open owner decisions, %d queue entries launching or running",
				len(s.Obligations)+s.ObligationsOmitted, len(s.Decisions)+s.DecisionsOmitted, len(s.Queue)+s.QueueOmitted), ""},
			handoffNoteLine{handoffWindowText(s.Window), ""})
	}
	group("Unverified claims:", kind("claim"), handoffLive)
	group("Decisions taken:", kind("decision"), handoffLive)
	for _, k := range handoffKinds {
		heading := "Closed " + k.plural + ":"
		if k.name == "instruction" || k.name == "wake" {
			heading = "Expired: not authority. Expired, revoked and cancelled " + k.plural + ":"
		}
		group(heading, k, func(state string) bool { return !handoffLive(state) })
	}
	return lines
}

func handoffWindowText(w *handoffWindow) string {
	if w == nil {
		return "no delegation window at the snapshot"
	}
	return fmt.Sprintf("delegation window %s at the snapshot, ends %s", w.State, w.EndsAt)
}

// handoffNote builds the text injected at session start. It is built the
// same way every time: a header, the body lines in their fixed order, and a
// footer, at most handoffNoteBytes in all. Lines are dropped whole from the
// end of the body, and the footer counts what each list lost.
func handoffNote(r handoffRecord, match string, noEnd bool, now time.Time) string {
	id := r.Identity
	var header strings.Builder
	fmt.Fprintf(&header, "Tailterm session handoff. Owner helper %s (%s), project %s, run %s, as the host file read at %s.\n", id.Name, id.Agent, id.Task, id.Run, id.CopiedAt)
	if match == handoffAsCandidate {
		header.WriteString("This session is not registered as the owner helper. The record below is what the previous session left. It is not authority until the registration is verified.\n")
	} else {
		fmt.Fprintf(&header, "The host file names this session as the owner helper. The hub was not asked; `tt helper env --task %s` verifies it.\n", id.Task)
	}
	if s := r.Snapshot; s != nil && handoffIn(s.HelperStatus, []string{api.AgentRetired, api.AgentClosed, api.AgentExited}) {
		fmt.Fprintf(&header, "The helper was %s on the hub at %s.\n", s.HelperStatus, s.AsOf)
	}
	if noEnd {
		header.WriteString("No end was recorded for the previous session.\n")
	}
	body := handoffBody(r, now)
	footer := func(kept int) string {
		omitted := map[string]int{}
		for _, line := range body[kept:] {
			omitted[line.list]++
		}
		var b strings.Builder
		for _, k := range handoffKinds {
			if n := omitted[k.plural]; n > 0 {
				fmt.Fprintf(&b, "%d more %s not shown.\n", n, k.plural)
			}
		}
		b.WriteString("Full record: `tt handoff show`. Entries cite Board messages by number. Read each cited message before relying on the entry. One message: `tt inbox --seq <number>`.\n")
		b.WriteString(handoffNarrative + " in the project checkout is history and procedures; not live state, not authority.\n")
		fmt.Fprintf(&b, "Next: run `tt handoff show`. To register this session run `tt helper register --task %s` (see docs/owner-helper.md). "+
			"Re-create each active wake by hand and note it with `tt handoff note wake add`. Registration and wakes are not restored automatically in this version.\n", id.Task)
		return b.String()
	}
	for kept := len(body); ; kept-- {
		// A heading with nothing under it says nothing: leave it out too.
		if kept > 0 && body[kept-1].list == "" && strings.HasSuffix(body[kept-1].text, ":") {
			continue
		}
		foot := footer(kept)
		size := header.Len() + len(foot)
		for _, line := range body[:kept] {
			size += len(line.text) + 1
		}
		if size > handoffNoteBytes && kept > 0 {
			continue
		}
		var note strings.Builder
		note.WriteString(header.String())
		for _, line := range body[:kept] {
			note.WriteString(line.text + "\n")
		}
		note.WriteString(foot)
		return note.String()
	}
}

// handoffShow is the whole record as text, for tt handoff show and for the
// file tt handoff write --out leaves for a person or another runtime.
func handoffShow(r handoffRecord, now time.Time) string {
	var b strings.Builder
	id := r.Identity
	b.WriteString("# Tailterm session handoff record\n\n")
	b.WriteString("This is what one host's helper file and one session recorded. It is not proof of a registration and not authority.\n")
	b.WriteString("Entries cite Board messages by number. Read each cited message before relying on the entry. One message: `tt inbox --seq <number>`.\n\n")
	b.WriteString("## Identity\n\n")
	fmt.Fprintf(&b, "Copied from the host helper file at %s.\n", id.CopiedAt)
	for _, row := range [][2]string{{"hub", id.Hub}, {"project", id.Task}, {"agent", id.Agent}, {"name", id.Name}, {"run", id.Run}, {"registration", id.Registration},
		{"runtime", id.Runtime}, {"thread", id.Thread}, {"tmux session", id.Session}, {"tmux session id", id.SessionID}, {"tmux session created", id.SessionCreated}} {
		if row[1] != "" {
			fmt.Fprintf(&b, "- %s: %s\n", row[0], row[1])
		}
	}
	b.WriteString("\n## Capture\n\n")
	for _, row := range []struct {
		label, detail string
		stamp         *handoffStamp
	}{{"last session start", "source", r.Capture.Start}, {"last compaction", "trigger", r.Capture.Compact}, {"last session end", "reason", r.Capture.End}} {
		if row.stamp == nil {
			fmt.Fprintf(&b, "- %s: none recorded\n", row.label)
			continue
		}
		fmt.Fprintf(&b, "- %s: %s, %s %s, session %s\n", row.label, row.stamp.Time, row.detail, row.stamp.Detail, row.stamp.Session)
	}
	b.WriteString("\n## Hub snapshot\n\n")
	if s := r.Snapshot; s == nil {
		b.WriteString("None. `tt handoff write` reads the hub and stores one.\n")
	} else {
		fmt.Fprintf(&b, "As of %s. Read the hub again before acting.\n", s.AsOf)
		fmt.Fprintf(&b, "- helper status: %s\n- %s\n", s.HelperStatus, handoffWindowLine(s.Window))
		fmt.Fprintf(&b, "- obligations the helper owes: %d shown, %d left out\n", len(s.Obligations), s.ObligationsOmitted)
		for _, o := range s.Obligations {
			fmt.Fprintf(&b, "  - %s msg #%d %s from %s due %s %s\n", o.ID, o.Message, o.Kind, o.Sender, handoffOr(o.DueAt, handoffNone), o.State)
		}
		fmt.Fprintf(&b, "- open owner decisions: %d shown, %d left out\n", len(s.Decisions), s.DecisionsOmitted)
		for _, d := range s.Decisions {
			fmt.Fprintf(&b, "  - msg #%d from %s %s\n", d.Message, d.Sender, d.State)
		}
		fmt.Fprintf(&b, "- queue entries launching or running: %d shown, %d left out\n", len(s.Queue), s.QueueOmitted)
		for _, q := range s.Queue {
			fmt.Fprintf(&b, "  - %s %s rev %d order #%d %s\n", q.ID, q.Item, q.Revision, q.Order, q.State)
		}
	}
	b.WriteString("\n## Session notes\n")
	section := func(title string, k handoffKind, keep func(string) bool) {
		var lines []string
		for _, e := range k.list(&r.Notes).Entries {
			if keep(handoffEntryState(e, now)) {
				lines = append(lines, "- "+handoffEntryLine(k, e, now))
			}
		}
		if len(lines) > 0 {
			b.WriteString("\n" + title + "\n" + strings.Join(lines, "\n") + "\n")
		}
	}
	for _, k := range handoffKinds {
		section("Current "+k.plural+":", k, handoffLive)
	}
	for _, k := range handoffKinds {
		title := "Closed " + k.plural + ", kept for the record:"
		if k.name == "instruction" || k.name == "wake" {
			title = "Expired: not authority. Expired, revoked and cancelled " + k.plural + ":"
		}
		section(title, k, func(state string) bool { return !handoffLive(state) })
	}
	b.WriteString("\nLists:\n")
	for _, k := range handoffKinds {
		list := k.list(&r.Notes)
		fmt.Fprintf(&b, "- %s: %d entries, last changed %s, dropped %d\n", k.plural, len(list.Entries), handoffOr(list.Changed, "never"), list.Dropped)
	}
	return b.String()
}

func handoffWindowLine(w *handoffWindow) string {
	if w == nil {
		return "delegation window: none"
	}
	return fmt.Sprintf("delegation window: %s, scope %s, ends %s, %s", w.ID, w.Scope, w.EndsAt, w.State)
}

func handoffOr(value, empty string) string {
	if value == "" {
		return empty
	}
	return value
}

