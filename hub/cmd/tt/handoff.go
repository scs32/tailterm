func (s handoffStore) path(name string) string { return filepath.Join(s.dir, name) }

// prepare creates the record directory, private to the user.
func (s handoffStore) prepare() error {
	root := filepath.Dir(s.dir)
	for _, dir := range []string{root, s.dir} {
		handoffTouch(dir)
		if err := os.MkdirAll(dir, 0700); err != nil {
			return err
		}
		if err := os.Chmod(dir, 0700); err != nil {
			return err
		}
	}
	return nil
}

// lock returns the unlock function, or nil when the lock was not obtained in
// time. The lock ends with the process, so a killed hook leaves none behind.
func (s handoffStore) lock() func() {
	path := s.path("handoff.lock")
	handoffTouch(path)
	f, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, 0600)
	if err != nil {
		return nil
	}
	for waited := time.Duration(0); ; waited += handoffLockRetry {
		err = syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB)
		if err == nil {
			return func() { _ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN); _ = f.Close() }
		}
		if (!errors.Is(err, syscall.EWOULDBLOCK) && !errors.Is(err, syscall.EAGAIN)) || waited >= s.lockWait {
			_ = f.Close()
			return nil
		}
		time.Sleep(handoffLockRetry)
	}
}

var (
	errHandoffNoRecord  = errors.New("no handoff record")
	errHandoffBadRecord = errors.New("the handoff record holds a value tt did not write; move it aside and start again")
)

// load reads record.json and the bytes it was read from.
func (s handoffStore) load() (handoffRecord, []byte, error) {
	path := s.path("record.json")
	handoffTouch(path)
	f, err := os.Open(path)
	if errors.Is(err, os.ErrNotExist) {
		return handoffRecord{}, nil, errHandoffNoRecord
	}
	if err != nil {
		return handoffRecord{}, nil, err
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, int64(handoffMaxBytes)+1))
	if err != nil {
		return handoffRecord{}, nil, err
	}
	var r handoffRecord
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if len(data) > handoffMaxBytes || dec.Decode(&r) != nil || !r.valid() {
		return handoffRecord{}, nil, errHandoffBadRecord
	}
	return r, data, nil
}

// save replaces record.json by write-to-temporary and rename, keeping the
// bytes it replaces as record.json.1. A record over the size bound is
// refused, naming the largest list.
func (s handoffStore) save(r handoffRecord, previous []byte) error {
	for _, k := range handoffKinds {
		if list := k.list(&r.Notes); list.Entries == nil {
			list.Entries = []handoffEntry{} // an empty list is stored as [], never null
		}
	}
	data, err := json.Marshal(r)
	if err != nil {
		return err
	}
	data = append(data, '\n')
	if len(data) > handoffMaxBytes {
		return fmt.Errorf("the record would pass %d bytes; the %s list is full: close or drop entries first", handoffMaxBytes, r.largestList())
	}
	if !r.valid() {
		return errHandoffBadRecord
	}
	path := s.path("record.json")
	if previous != nil {
		if err := s.replace(path+".1", previous); err != nil {
			return err
		}
	}
	return s.replace(path, data)
}

func (s handoffStore) replace(path string, data []byte) error {
	tmp := fmt.Sprintf("%s.tmp-%d", path, os.Getpid())
	handoffTouch(tmp)
	if err := os.WriteFile(tmp, data, 0600); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	handoffTouch(path)
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}

func (r handoffRecord) largestList() string {
	name, most := "notes", 0
	size := func(label string, v any) {
		if data, err := json.Marshal(v); err == nil && len(data) > most {
			name, most = label, len(data)
		}
	}
	for _, k := range handoffKinds {
		size(k.plural, k.list(&r.Notes).Entries)
	}
	if r.Snapshot != nil {
		size("snapshot obligations", r.Snapshot.Obligations)
		size("snapshot decisions", r.Snapshot.Decisions)
		size("snapshot queue", r.Snapshot.Queue)
	}
	return name
}

// appendCapture adds one line to captures.jsonl, rotating it at the size
// bound. The caller holds the lock.
func (s handoffStore) appendCapture(event string, stamp handoffStamp, match string) {
	line, err := json.Marshal(struct {
		V       int    `json:"v"`
		Time    string `json:"time"`
		Event   string `json:"event"`
		Detail  string `json:"detail"`
		Session string `json:"session,omitempty"`
		Match   string `json:"match"`
	}{1, stamp.Time, event, stamp.Detail, stamp.Session, match})
	if err != nil {
		return
	}
	path := s.path("captures.jsonl")
	handoffTouch(path)
	if info, err := os.Stat(path); err == nil && info.Size() >= handoffCaptureMax {
		handoffTouch(path + ".1")
		_ = os.Rename(path, path+".1")
	}
	f, err := os.OpenFile(path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0600)
	if err != nil {
		return
	}
	_, _ = f.Write(append(line, '\n'))
	_ = f.Close()
}

