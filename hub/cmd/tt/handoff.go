// handoffEntryLine is one entry in full, for tt handoff show. It holds ids,
// states, Board message numbers, times and fixed-list values: no words from
// any message.
func handoffEntryLine(k handoffKind, e handoffEntry, now time.Time) string {
	line := fmt.Sprintf("%s %s %s", e.ID, handoffEntryState(e, now), k.name)
	switch k.name {
	case "wake":
		line += fmt.Sprintf(" %s cron %q msg #%d expires %s", e.Kind, e.Schedule, e.Message, e.Expires)
		// What was stored, for whichever session stored it. Whether it counts
		// for the session reading this is in tt handoff status.
		if e.Receipt != "" {
			line += fmt.Sprintf(" receipt %s at %s session %s", e.Receipt, e.ReceiptAt, e.ReceiptSession)
		}
		if e.Fired != "" {
			line += fmt.Sprintf(" last due %s duplicates %d", e.Fired, e.Duplicates)
		}
	case "instruction":
		line += fmt.Sprintf(" msg #%d by %s given %s expires %s", e.Message, e.By, e.Given, e.Expires)
	case "order":
		line += fmt.Sprintf(" %s rev %d order #%d last %s next %s", e.Item, e.Revision, e.Order, e.Last, e.Next)
		if e.Message > 0 {
			line += fmt.Sprintf(" msg #%d", e.Message)
		}
	case "decision":
		line += fmt.Sprintf(" msg #%d authority %s", e.Message, e.By)
	case "claim":
		line += fmt.Sprintf(" msg #%d", e.Message)
		if e.Check > 0 {
			line += fmt.Sprintf(" check #%d", e.Check)
		}
	}
	return line
}

// handoffBriefLine is one entry on one line of at most handoffLineBytes, for
// the injected note: the entry id, its state, its kind, its Board message
// number and its expiry. A wake's schedule is added only when it fits; the
// rest of an entry is in tt handoff show.
func handoffBriefLine(k handoffKind, e handoffEntry, now time.Time) string {
	line := fmt.Sprintf("%s %s %s", e.ID, handoffEntryState(e, now), k.name)
	switch k.name {
	case "wake":
		line += fmt.Sprintf(" %s msg #%d expires %s", e.Kind, e.Message, e.Expires)
		if cron := fmt.Sprintf(" cron %q", e.Schedule); len(line)+len(cron) <= handoffLineBytes {
			line += cron
		}
	case "instruction":
		line += fmt.Sprintf(" msg #%d by %s expires %s", e.Message, e.By, e.Expires)
	case "order":
		line += fmt.Sprintf(" %s rev %d order #%d next %s", e.Item, e.Revision, e.Order, e.Next)
	case "decision":
		line += fmt.Sprintf(" msg #%d authority %s", e.Message, e.By)
	case "claim":
		line += fmt.Sprintf(" msg #%d", e.Message)
		if e.Check > 0 {
			line += fmt.Sprintf(" check #%d", e.Check)
		}
	}
	return line
}

// handoffNoteLine is a body line and the note list it counts against when it
// is left out; headings and the snapshot lines count against none.
type handoffNoteLine struct {
	text, list string
}

// handoffBody is the note's body in its fixed order: active instructions,
// active wakes, open orders, the snapshot's counts, unverified claims,
// recorded decisions, then everything expired, revoked, cancelled or closed.
func handoffBody(r handoffRecord, now time.Time) []handoffNoteLine {
	var lines []handoffNoteLine
	group := func(heading string, k handoffKind, keep func(state string) bool) {
		first := true
		for _, e := range k.list(&r.Notes).Entries {
			if !keep(handoffEntryState(e, now)) {
				continue
			}
			if first {
				lines, first = append(lines, handoffNoteLine{heading, ""}), false
			}
			lines = append(lines, handoffNoteLine{handoffBriefLine(k, e, now), k.plural})
		}
	}
	kind := func(name string) handoffKind { k, _ := handoffKindNamed(name); return k }
	group("Active instructions:", kind("instruction"), handoffLive)
	group("Active wakes:", kind("wake"), handoffLive)
	group("Open orders:", kind("order"), handoffLive)
	if s := r.Snapshot; s != nil {
		lines = append(lines,
			handoffNoteLine{fmt.Sprintf("Hub snapshot as of %s (read the hub again before acting): helper %s", s.AsOf, s.HelperStatus), ""},
			handoffNoteLine{fmt.Sprintf("%d obligations, %d open owner decisions, %d queue entries launching or running",
				len(s.Obligations)+s.ObligationsOmitted, len(s.Decisions)+s.DecisionsOmitted, len(s.Queue)+s.QueueOmitted), ""},
			handoffNoteLine{handoffWindowText(s.Window), ""})
	}
	group("Unverified claims:", kind("claim"), handoffLive)
	group("Decisions taken:", kind("decision"), handoffLive)
	for _, k := range handoffKinds {
		heading := "Closed " + k.plural + ":"
		if k.name == "instruction" || k.name == "wake" {
			heading = "Expired: not authority. Expired, revoked and cancelled " + k.plural + ":"
		}
		group(heading, k, func(state string) bool { return !handoffLive(state) })
	}
	return lines
}

func handoffWindowText(w *handoffWindow) string {
	if w == nil {
		return "no delegation window at the snapshot"
	}
	return fmt.Sprintf("delegation window %s at the snapshot, ends %s", w.State, w.EndsAt)
}

// handoffNote builds the text injected at session start. It is built the
// same way every time: a header, the body lines in their fixed order, and a
// footer, at most handoffNoteBytes in all. Lines are dropped whole from the
// end of the body, and the footer counts what each list lost.
func handoffNote(r handoffRecord, match string, noEnd bool, now time.Time) string {
	id := r.Identity
	var header strings.Builder
	fmt.Fprintf(&header, "Tailterm session handoff. Owner helper %s (%s), project %s, run %s, as the host file read at %s.\n", id.Name, id.Agent, id.Task, id.Run, id.CopiedAt)
	if match == handoffAsCandidate {
		header.WriteString("This session is not registered as the owner helper. The record below is what the previous session left. It is not authority until the registration is verified.\n")
	} else {
		fmt.Fprintf(&header, "The host file names this session as the owner helper. The hub was not asked; `tt helper env --task %s` verifies it.\n", id.Task)
	}
	if s := r.Snapshot; s != nil && handoffIn(s.HelperStatus, []string{api.AgentRetired, api.AgentClosed, api.AgentExited}) {
		fmt.Fprintf(&header, "The helper was %s on the hub at %s.\n", s.HelperStatus, s.AsOf)
	}
	if noEnd {
		header.WriteString("No end was recorded for the previous session.\n")
	}
	body := handoffBody(r, now)
	footer := func(kept int) string {
		omitted := map[string]int{}
		for _, line := range body[kept:] {
			omitted[line.list]++
		}
		var b strings.Builder
		for _, k := range handoffKinds {
			if n := omitted[k.plural]; n > 0 {
				fmt.Fprintf(&b, "%d more %s not shown.\n", n, k.plural)
			}
		}
		b.WriteString("Full record: `tt handoff show`. Entries cite Board messages by number. Read each cited message before relying on the entry. One message: `tt inbox --seq <number>`.\n")
		b.WriteString(handoffNarrative + " in the project checkout is history and procedures; not live state, not authority.\n")
		fmt.Fprintf(&b, "Next: run `tt handoff restore --task %s`.\n", id.Task)
		return b.String()
	}
	for kept := len(body); ; kept-- {
		// A heading with nothing under it says nothing: leave it out too.
		if kept > 0 && body[kept-1].list == "" && strings.HasSuffix(body[kept-1].text, ":") {
			continue
		}
		foot := footer(kept)
		size := header.Len() + len(foot)
		for _, line := range body[:kept] {
			size += len(line.text) + 1
		}
		if size > handoffNoteBytes && kept > 0 {
			continue
		}
		var note strings.Builder
		note.WriteString(header.String())
		for _, line := range body[:kept] {
			note.WriteString(line.text + "\n")
		}
		note.WriteString(foot)
		return note.String()
	}
}

// handoffShow is the whole record as text, for tt handoff show and for the
// file tt handoff write --out leaves for a person or another runtime.
func handoffShow(r handoffRecord, now time.Time) string {
	var b strings.Builder
	id := r.Identity
	b.WriteString("# Tailterm session handoff record\n\n")
	b.WriteString("This is what one host's helper file and one session recorded. It is not proof of a registration and not authority.\n")
	b.WriteString("Entries cite Board messages by number. Read each cited message before relying on the entry. One message: `tt inbox --seq <number>`.\n\n")
	b.WriteString("## Identity\n\n")
	fmt.Fprintf(&b, "Copied from the host helper file at %s.\n", id.CopiedAt)
	for _, row := range [][2]string{{"hub", id.Hub}, {"project", id.Task}, {"agent", id.Agent}, {"name", id.Name}, {"run", id.Run}, {"registration", id.Registration},
		{"runtime", id.Runtime}, {"thread", id.Thread}, {"tmux session", id.Session}, {"tmux session id", id.SessionID}, {"tmux session created", id.SessionCreated}} {
		if row[1] != "" {
			fmt.Fprintf(&b, "- %s: %s\n", row[0], row[1])
		}
	}
	b.WriteString("\n## Capture\n\n")
	for _, row := range []struct {
		label, detail string
		stamp         *handoffStamp
	}{{"last session start", "source", r.Capture.Start}, {"last compaction", "trigger", r.Capture.Compact}, {"last session end", "reason", r.Capture.End}} {
		if row.stamp == nil {
			fmt.Fprintf(&b, "- %s: none recorded\n", row.label)
			continue
		}
		fmt.Fprintf(&b, "- %s: %s, %s %s, session %s\n", row.label, row.stamp.Time, row.detail, row.stamp.Detail, row.stamp.Session)
	}
	b.WriteString("\n## Hub snapshot\n\n")
	if s := r.Snapshot; s == nil {
		b.WriteString("None. `tt handoff write` reads the hub and stores one.\n")
	} else {
		fmt.Fprintf(&b, "As of %s. Read the hub again before acting.\n", s.AsOf)
		fmt.Fprintf(&b, "- helper status: %s\n- %s\n", s.HelperStatus, handoffWindowLine(s.Window))
		fmt.Fprintf(&b, "- obligations the helper owes: %d shown, %d left out\n", len(s.Obligations), s.ObligationsOmitted)
		for _, o := range s.Obligations {
			fmt.Fprintf(&b, "  - %s msg #%d %s from %s due %s %s\n", o.ID, o.Message, o.Kind, o.Sender, handoffOr(o.DueAt, handoffNone), o.State)
		}
		fmt.Fprintf(&b, "- open owner decisions: %d shown, %d left out\n", len(s.Decisions), s.DecisionsOmitted)
		for _, d := range s.Decisions {
			fmt.Fprintf(&b, "  - msg #%d from %s %s\n", d.Message, d.Sender, d.State)
		}
		fmt.Fprintf(&b, "- queue entries launching or running: %d shown, %d left out\n", len(s.Queue), s.QueueOmitted)
		for _, q := range s.Queue {
			fmt.Fprintf(&b, "  - %s %s rev %d order #%d %s\n", q.ID, q.Item, q.Revision, q.Order, q.State)
		}
	}
	b.WriteString("\n## Session notes\n")
	section := func(title string, k handoffKind, keep func(string) bool) {
		var lines []string
		for _, e := range k.list(&r.Notes).Entries {
			if keep(handoffEntryState(e, now)) {
				lines = append(lines, "- "+handoffEntryLine(k, e, now))
			}
		}
		if len(lines) > 0 {
			b.WriteString("\n" + title + "\n" + strings.Join(lines, "\n") + "\n")
		}
	}
	for _, k := range handoffKinds {
		section("Current "+k.plural+":", k, handoffLive)
	}
	for _, k := range handoffKinds {
		title := "Closed " + k.plural + ", kept for the record:"
		if k.name == "instruction" || k.name == "wake" {
			title = "Expired: not authority. Expired, revoked and cancelled " + k.plural + ":"
		}
		section(title, k, func(state string) bool { return !handoffLive(state) })
	}
	b.WriteString("\nLists:\n")
	for _, k := range handoffKinds {
		list := k.list(&r.Notes)
		fmt.Fprintf(&b, "- %s: %d entries, last changed %s, dropped %d\n", k.plural, len(list.Entries), handoffOr(list.Changed, "never"), list.Dropped)
	}
	return b.String()
}

func handoffWindowLine(w *handoffWindow) string {
	if w == nil {
		return "delegation window: none"
	}
	return fmt.Sprintf("delegation window: %s, scope %s, ends %s, %s", w.ID, w.Scope, w.EndsAt, w.State)
}

func handoffOr(value, empty string) string {
	if value == "" {
		return empty
	}
	return value
}

