// ---- the setting ----

func handoffConfigPath() string {
	if path := os.Getenv("TAILTERM_HANDOFF_CONFIG"); path != "" {
		return path
	}
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		return ""
	}
	return filepath.Join(home, ".config", "tailterm", "handoff.json")
}

// handoffOn reads the host setting at each use. A missing or unreadable file,
// malformed JSON, a missing key and any value other than the exact string
// "on" mean off. The key is read by its exact name from a map: encoding/json
// would match a struct field without regard to case.
func handoffOn() bool {
	path := handoffConfigPath()
	if path == "" {
		return false
	}
	handoffTouch(path)
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, 64<<10+1))
	if err != nil || len(data) > 64<<10 {
		return false
	}
	var config map[string]json.RawMessage
	var value string
	return json.Unmarshal(data, &config) == nil && json.Unmarshal(config[handoffSettingKey], &value) == nil && value == "on"
}

func handoffOffError() error {
	return fmt.Errorf("session handoff is off on this host: set %q to \"on\" in %s", handoffSettingKey, handoffConfigPath())
}

// handoffTouch reports a path before this file opens, lists, creates or
// renames it. TAILTERM_HANDOFF_ACCESS_LOG names a file that receives one path
// per line; the live check uses it to prove where the hook reached.
func handoffTouch(path string) {
	if handoffAccessHook != nil {
		handoffAccessHook(path)
	}
	log := os.Getenv("TAILTERM_HANDOFF_ACCESS_LOG")
	if log == "" {
		return
	}
	if f, err := os.OpenFile(log, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0600); err == nil {
		_, _ = f.WriteString(path + "\n")
		_ = f.Close()
	}
}

