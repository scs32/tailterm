// latestStart is the latest SessionStart captured for one runtime session: in
// the record when that session is the registered one, and in the capture log
// otherwise. A start of any source counts, so a compaction, a clear, a resume
// or a fork puts every earlier receipt before it.
func (s handoffStore) latestStart(r handoffRecord, session string) (handoffStamp, bool) {
	var latest handoffStamp
	found := false
	consider := func(stamp handoffStamp) {
		if !strings.EqualFold(stamp.Session, session) || !handoffTimeOK(stamp.Time) || stamp.Detail != handoffOther && !handoffIn(stamp.Detail, handoffStartSources) {
			return
		}
		if !found || stamp.Time > latest.Time {
			latest, found = stamp, true
		}
	}
	if r.Capture.Start != nil {
		consider(*r.Capture.Start)
	}
	for _, name := range []string{"captures.jsonl.1", "captures.jsonl"} {
		path := s.path(name)
		handoffTouch(path)
		f, err := os.Open(path)
		if err != nil {
			continue
		}
		lines := bufio.NewScanner(io.LimitReader(f, 2*handoffCaptureMax+1<<20))
		lines.Buffer(make([]byte, 0, 4096), 4096)
		for lines.Scan() {
			var row struct {
				Time, Event, Detail, Session string
			}
			if json.Unmarshal(lines.Bytes(), &row) == nil && row.Event == "SessionStart" {
				consider(handoffStamp{Time: row.Time, Detail: row.Detail, Session: strings.ToLower(row.Session)})
			}
		}
		_ = f.Close()
	}
	return latest, found
}

// sessionStart is the start a wake receipt is judged against for one Claude
// Code session: the latest captured start, moved up to the session's floor
// when that is later. unknown is the reason the floor could not be read; no
// receipt counts then. Another runtime has no session timer and is not read.
func (s handoffStore) sessionStart(r handoffRecord, runtime, session string) (start handoffStamp, started bool, unknown string) {
	start, started = s.latestStart(r, session)
	if runtime != "claude" {
		return start, started, ""
	}
	floor, unknown := handoffSessionFloor(session)
	if unknown == "" && started && floor > start.Time {
		start.Time = floor
	}
	return start, started, unknown
}

// handoffWakeFor is a wake's state for one runtime session, and the reason
// when it is not restored. An expired or cancelled wake keeps that state.
func handoffWakeFor(e handoffEntry, runtime, session string, start handoffStamp, started bool, unknown string, now time.Time) (state, reason string) {
	if state := handoffEntryState(e, now); state != "active" {
		return state, ""
	}
	switch {
	case runtime != "claude":
		return handoffNotRestored, "no-session-timer"
	case e.Receipt == "":
		return handoffNotRestored, "no-receipt"
	case !strings.EqualFold(e.ReceiptSession, session):
		return handoffNotRestored, "another-session"
	case unknown != "":
		return handoffNotRestored, unknown
	case !started:
		return handoffNotRestored, "no-start-captured"
	case e.ReceiptAt <= start.Time:
		// Both are kept to the second: a receipt in the same second as a
		// start is not known to be after it.
		return handoffNotRestored, "earlier-start"
	}
	return e.Receipt, ""
}

// handoffLedgerRow finds the tool-ledger row that proves this session created
// one wake's cron: the cron tool, outcome ok, this session, the digest of the
// printed arguments, later than the session's latest start, and not already
// backing another wake. It reads the helper's ledger and its one rotated file.
func handoffLedgerRow(agent, session, digest string, after time.Time, used map[string]bool) (toolUse string, at time.Time, ok bool) {
	root := toolLedgerRoot()
	if root == "" || !toolLedgerAgentOK(agent) || digest == "" {
		return "", time.Time{}, false
	}
	for _, name := range []string{"ledger.jsonl.1", "ledger.jsonl"} {
		path := filepath.Join(root, agent, name)
		handoffTouch(path)
		f, err := os.Open(path)
		if err != nil {
			continue
		}
		data, err := io.ReadAll(io.LimitReader(f, 4*toolLedgerMaxBytes))
		_ = f.Close()
		if err != nil {
			continue
		}
		for _, line := range bytes.Split(data, []byte("\n")) {
			var row toolLedgerRow
			if len(line) == 0 || json.Unmarshal(line, &row) != nil {
				continue
			}
			if row.Agent != agent || !strings.EqualFold(row.Session, session) || row.Tool != handoffCronTool || row.Outcome != "ok" ||
				row.ArgsDigest != digest || !handoffToolUsePattern.MatchString(row.ToolUseID) || used[row.ToolUseID] {
				continue
			}
			// The start is kept to the second, so a row counts only from the
			// next second on.
			if t, err := time.Parse(time.RFC3339Nano, row.Time); err == nil && t.UTC().Truncate(time.Second).After(after) {
				return row.ToolUseID, t.UTC().Truncate(time.Second), true
			}
		}
	}
	return "", time.Time{}, false
}

// handoffCronSet is the values one cron field allows, and whether the field
// is unrestricted.
func handoffCronSet(field string, low, high int) (set map[int]bool, any bool) {
	set = map[int]bool{}
	for _, part := range strings.Split(field, ",") {
		base, stepText, stepped := strings.Cut(part, "/")
		step := 1
		if stepped {
			step, _ = handoffCronNumber(stepText)
		}
		from, to := low, high
		if base != "*" {
			a, b, ranged := strings.Cut(base, "-")
			from, _ = handoffCronNumber(a)
			to = from
			if ranged {
				to, _ = handoffCronNumber(b)
			} else if stepped {
				to = high
			}
		}
		if step < 1 {
			step = 1
		}
		for v := from; v <= to; v += step {
			set[v] = true
		}
	}
	return set, field == "*"
}

// handoffCronPeriod is the time between the two firings of a stored schedule
// that follow now, or 0 when none is found within a year.
func handoffCronPeriod(schedule string, now time.Time) time.Duration {
	fields := strings.Fields(schedule)
	if len(fields) != 5 {
		return 0
	}
	minutes, _ := handoffCronSet(fields[0], 0, 59)
	hours, _ := handoffCronSet(fields[1], 0, 23)
	days, anyDay := handoffCronSet(fields[2], 1, 31)
	months, _ := handoffCronSet(fields[3], 1, 12)
	weekdays, anyWeekday := handoffCronSet(fields[4], 0, 7)
	if weekdays[7] {
		weekdays[0] = true
	}
	fires := func(t time.Time) bool {
		if !minutes[t.Minute()] || !hours[t.Hour()] || !months[int(t.Month())] {
			return false
		}
		day, weekday := days[t.Day()], weekdays[int(t.Weekday())]
		// cron's rule: with both day fields restricted, either one fires.
		if !anyDay && !anyWeekday {
			return day || weekday
		}
		return day && weekday
	}
	var first time.Time
	t := now.Truncate(time.Minute)
	for i := 0; i < 366*24*60*2; i++ {
		if t = t.Add(time.Minute); !fires(t) {
			continue
		}
		if first.IsZero() {
			first = t
			continue
		}
		return t.Sub(first)
	}
	return 0
}

// handoffWakeTarget is what a wake command acts on: the helper, the session
// the command speaks for and its runtime, and the record's store.
type handoffWakeTarget struct {
	helper           ownerHelperFile
	runtime, session string
	store            handoffStore
}

// handoffWakeCommandTarget parses `ID [flags]` for a wake command and finds the
// registered helper it may write for.
func handoffWakeCommandTarget(e env, name string, args []string, flags func(*flag.FlagSet)) (handoffWakeTarget, string, error) {
	if !handoffOn() {
		return handoffWakeTarget{}, "", handoffOffError()
	}
	if len(args) == 0 || !handoffEntryIDPattern.MatchString(args[0]) || !strings.HasPrefix(args[0], "w") {
		return handoffWakeTarget{}, "", errors.New("name the wake by its id, such as w1")
	}
	id := args[0]
	fs := handoffFlags(name)
	task := fs.String("task", e.task, "project id")
	if flags != nil {
		flags(fs)
	}
	if err := fs.Parse(args[1:]); err != nil || fs.NArg() > 0 {
		return handoffWakeTarget{}, "", errors.New(handoffUsage)
	}
	helper, err := handoffWriter(e, *task)
	if err != nil {
		return handoffWakeTarget{}, "", err
	}
	target := handoffWakeTarget{helper: helper, runtime: helper.Runtime, session: strings.ToLower(helper.Thread)}
	// handoffWriter has checked that a runtime session, when there is one, is
	// the registered thread. A shell with none is the owner typing by hand and
	// speaks for that thread.
	store, ok := handoffStoreFor(helper.Agent, handoffCommandLockWait)
	if !ok {
		return handoffWakeTarget{}, "", errors.New("no handoff state directory")
	}
	target.store = store
	return target, id, nil
}

// handoffWakeEdit loads the record under its lock, hands the named wake to
// edit and saves the record when edit says it changed.
func (w handoffWakeTarget) edit(id string, edit func(r handoffRecord, entry *handoffEntry, now time.Time) (bool, error)) error {
	if err := w.store.prepare(); err != nil {
		return err
	}
	unlock := w.store.lock()
	if unlock == nil {
		return errors.New("the handoff record is locked by another command; try again")
	}
	defer unlock()
	r, previous, err := w.store.load()
	if errors.Is(err, errHandoffNoRecord) {
		return fmt.Errorf("no wake %s in the record", id)
	}
	if err != nil {
		return err
	}
	list := &r.Notes.Wakes
	for i := range list.Entries {
		if list.Entries[i].ID != id {
			continue
		}
		changed, err := edit(r, &list.Entries[i], handoffNow())
		if changed {
			if saveErr := w.store.save(r, previous); saveErr != nil {
				return saveErr
			}
		}
		return err
	}
	return fmt.Errorf("no wake %s in the record", id)
}

// handoffWakeConfirmCommand records that this session holds one wake's cron.
// Without --asserted it only searches the tool ledger: it takes no cron id or
// other value from the session. With --asserted it records the session's word
// as exactly that.
func handoffWakeConfirmCommand(e env, args []string) error {
	var asserted *bool
	w, id, err := handoffWakeCommandTarget(e, "handoff wake confirm", args, func(fs *flag.FlagSet) {
		asserted = fs.Bool("asserted", false, "record the session's own statement, which is not verified")
	})
	if err != nil {
		return err
	}
	if w.runtime != "claude" {
		return fmt.Errorf("wake %s not restored: %s", id, handoffReasons["no-session-timer"])
	}
	return w.edit(id, func(r handoffRecord, entry *handoffEntry, now time.Time) (bool, error) {
		if state := handoffEntryState(*entry, now); state != "active" {
			return false, fmt.Errorf("wake %s is %s: it is not offered for re-creation and nothing was recorded", id, state)
		}
		start, started, unknown := w.store.sessionStart(r, w.runtime, w.session)
		if state, _ := handoffWakeFor(*entry, w.runtime, w.session, start, started, unknown, now); state == handoffRestored {
			fmt.Printf("wake %s restored: this session created its cron at %s (tool use %s)\n", id, entry.ReceiptAt, entry.ReceiptTool)
			return false, nil
		}
		if *asserted {
			entry.Receipt, entry.ReceiptSession, entry.ReceiptTool, entry.ReceiptAt = handoffAsserted, w.session, "", handoffStamped(now)
			fmt.Printf("wake %s session-asserted, not verified: tt did not see its cron created\n", id)
			return true, nil
		}
		if !handoffLedgerMatching {
			return false, fmt.Errorf("wake %s not restored: tool-ledger matching is off in this version, so no cron can be verified. Run `tt handoff wake confirm %s --asserted --task %s` to record it as session-asserted", id, id, w.helper.Task)
		}
		if unknown != "" {
			return false, fmt.Errorf("wake %s not restored: %s", id, handoffReasons[unknown])
		}
		if !started {
			return false, fmt.Errorf("wake %s not restored: %s", id, handoffReasons["no-start-captured"])
		}
		used := map[string]bool{}
		for _, other := range r.Notes.Wakes.Entries {
			if other.ID != id && other.ReceiptTool != "" {
				used[other.ReceiptTool] = true
			}
		}
		after, _ := time.Parse(handoffTimeLayout, start.Time)
		toolUse, at, ok := handoffLedgerRow(w.helper.Agent, w.session, toolArgsDigest(handoffWakeArgs(*entry, w.helper.Task)), after, used)
		if !ok {
			return false, fmt.Errorf("wake %s not restored: no tool-ledger row shows this session creating a cron with the printed arguments since its latest start (%s)", id, start.Time)
		}
		entry.Receipt, entry.ReceiptSession, entry.ReceiptTool, entry.ReceiptAt = handoffRestored, w.session, toolUse, handoffStamped(at)
		fmt.Printf("wake %s restored: this session created its cron at %s (tool use %s)\n", id, entry.ReceiptAt, toolUse)
		return true, nil
	})
}

// handoffWakeDueCommand is what every wake's cron runs. It prints what the wake
// is for, by kind and Board message number, records the firing, and reports a
// second firing within half the schedule's period as a duplicate cron.
func handoffWakeDueCommand(e env, args []string) error {
	w, id, err := handoffWakeCommandTarget(e, "handoff wake due", args, nil)
	if err != nil {
		return err
	}
	return w.edit(id, func(r handoffRecord, entry *handoffEntry, now time.Time) (bool, error) {
		if state := handoffEntryState(*entry, now); state != "active" {
			return false, fmt.Errorf("wake %s is %s: nothing is due. Delete its cron", id, state)
		}
		duplicate := false
		if last, err := time.Parse(handoffTimeLayout, entry.Fired); err == nil {
			if period := handoffCronPeriod(entry.Schedule, last); period > 0 && now.Sub(last) < period/2 {
				duplicate = true
				entry.Duplicates++
			}
		}
		entry.Fired = handoffStamped(now)
		fmt.Printf("wake %s due: %s, Board message #%d. Read it with `tt inbox --seq %d` before acting.\n", id, entry.Kind, entry.Message, entry.Message)
		if duplicate {
			fmt.Printf("duplicate cron for wake %s: delete the extra one\n", id)
		}
		return true, nil
	})
}

// handoffWakeReport prints every wake's state for one session and returns the
// rows for restore.json, the number of active wakes that are not restored,
// and the duplicate firings recorded. With offer set, each active wake that is
// not restored comes with the exact arguments to create its cron with.
func handoffWakeReport(b *strings.Builder, s handoffStore, r handoffRecord, runtime, session string, offer bool, now time.Time) (rows []handoffRestoreWake, pending int, duplicates int64) {
	start, started, unknown := s.sessionStart(r, runtime, session)
	task := r.Identity.Task
	if len(r.Notes.Wakes.Entries) == 0 {
		b.WriteString("  none in the record\n")
	}
	for _, e := range r.Notes.Wakes.Entries {
		state, reason := handoffWakeFor(e, runtime, session, start, started, unknown, now)
		rows = append(rows, handoffRestoreWake{ID: e.ID, State: state, Reason: reason})
		duplicates += e.Duplicates
		what := fmt.Sprintf("%s msg #%d cron %q expires %s", e.Kind, e.Message, e.Schedule, e.Expires)
		switch state {
		case handoffRestored:
			fmt.Fprintf(b, "  %s restored: this session created its cron at %s (tool use %s). %s\n", e.ID, e.ReceiptAt, e.ReceiptTool, what)
		case handoffAsserted:
			pending++
			fmt.Fprintf(b, "  %s session-asserted, not verified (said at %s). %s\n", e.ID, e.ReceiptAt, what)
		case handoffNotRestored:
			pending++
			fmt.Fprintf(b, "  %s not restored: %s. %s\n", e.ID, handoffReasons[reason], what)
			if offer && runtime == "claude" {
				fmt.Fprintf(b, "    arguments for %s: %s\n", handoffCronTool, handoffWakeArgs(e, task))
			}
		default:
			fmt.Fprintf(b, "  %s %s: not offered for re-creation. %s\n", e.ID, state, what)
		}
		if e.Duplicates > 0 {
			fmt.Fprintf(b, "    duplicate cron for wake %s: %d firings came within half its period; delete the extra one\n", e.ID, e.Duplicates)
		}
	}
	if offer && pending > 0 && runtime == "claude" {
		b.WriteString("  For each wake that is not restored: list this session's crons. If one already has that wake's prompt, keep it and run\n" +
			"  `tt handoff wake confirm ID --asserted --task " + task + "`. Otherwise create it with exactly the arguments printed above and run\n")
		if handoffLedgerMatching {
			b.WriteString("  `tt handoff wake confirm ID --task " + task + "`.\n")
		} else {
			b.WriteString("  `tt handoff wake confirm ID --asserted --task " + task + "`: tool-ledger matching is off in this version, so a wake can only be session-asserted.\n")
		}
	}
	return rows, pending, duplicates
}

