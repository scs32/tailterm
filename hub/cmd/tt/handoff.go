// handoffRestoreReport is restore.json: the last restore's result. Like the
// record it holds only generated and validated values.
type handoffRestoreReport struct {
	V            int                  `json:"v"`
	At           string               `json:"at"`
	Task         string               `json:"task"`
	Agent        string               `json:"agent"`
	Run          string               `json:"run"`
	PreviousRun  string               `json:"previousRun,omitempty"`
	Registration string               `json:"registration,omitempty"`
	Runtime      string               `json:"runtime"`
	Session      string               `json:"session"`
	Steps        []handoffRestoreStep `json:"steps"`
	Hub          *handoffRestoreHub   `json:"hub,omitempty"`
	Wakes        []handoffRestoreWake `json:"wakes"`
	NotRestored  int                  `json:"notRestored"`
}

type handoffRestoreStep struct {
	Name   string `json:"name"`
	State  string `json:"state"`
	Reason string `json:"reason,omitempty"`
}

type handoffRestoreWake struct {
	ID     string `json:"id"`
	State  string `json:"state"`
	Reason string `json:"reason,omitempty"`
}

// handoffRestoreHub is the hub read's counts against the record's snapshot.
type handoffRestoreHub struct {
	AsOf              string `json:"asOf"`
	SnapshotAsOf      string `json:"snapshotAsOf,omitempty"`
	Obligations       int    `json:"obligations"`
	ObligationsClosed int    `json:"obligationsClosed"`
	ObligationsNew    int    `json:"obligationsNew"`
	Decisions         int    `json:"decisions"`
	DecisionsClosed   int    `json:"decisionsClosed"`
	DecisionsNew      int    `json:"decisionsNew"`
	Queue             int    `json:"queue"`
	QueueClosed       int    `json:"queueClosed"`
	QueueNew          int    `json:"queueNew"`
}

var (
	handoffStepNames  = []string{"registration", "wake-binding", "hub-state", "record"}
	handoffStepStates = []string{handoffRestored, handoffCorrect, handoffNotRestored}
	handoffWakeStates = []string{handoffRestored, handoffAsserted, handoffNotRestored, "expired", "cancelled"}
)

func (p handoffRestoreReport) valid() bool {
	reason := func(r string) bool { _, ok := handoffReasons[r]; return r == "" || ok }
	if p.V != 1 || !handoffTimeOK(p.At) || !api.ValidID(p.Task, "tsk") || !api.ValidID(p.Agent, "agt") || !handoffID(p.Run, "run") ||
		p.PreviousRun != "" && !handoffID(p.PreviousRun, "run") || p.Registration != "" && !handoffID(p.Registration, "ohr") ||
		!handoffIn(p.Runtime, handoffRuntimes) || !threadIDPattern.MatchString(p.Session) || p.NotRestored < 0 ||
		len(p.Steps) > len(handoffStepNames) || len(p.Wakes) > handoffListCap {
		return false
	}
	for _, s := range p.Steps {
		if !handoffIn(s.Name, handoffStepNames) || !handoffIn(s.State, handoffStepStates) || !reason(s.Reason) {
			return false
		}
	}
	for _, w := range p.Wakes {
		if !handoffEntryIDPattern.MatchString(w.ID) || !strings.HasPrefix(w.ID, "w") || !handoffIn(w.State, handoffWakeStates) || !reason(w.Reason) {
			return false
		}
	}
	if h := p.Hub; h != nil {
		if !handoffTimeOK(h.AsOf) || h.SnapshotAsOf != "" && !handoffTimeOK(h.SnapshotAsOf) {
			return false
		}
		for _, n := range []int{h.Obligations, h.ObligationsClosed, h.ObligationsNew, h.Decisions, h.DecisionsClosed, h.DecisionsNew, h.Queue, h.QueueClosed, h.QueueNew} {
			if n < 0 {
				return false
			}
		}
	}
	return true
}

var errHandoffBadReport = errors.New("the restore report holds a value tt did not write; run tt handoff restore again")

// loadRestore reads restore.json. ok is false when there is none.
func (s handoffStore) loadRestore() (report handoffRestoreReport, ok bool, err error) {
	path := s.path("restore.json")
	handoffTouch(path)
	f, err := os.Open(path)
	if errors.Is(err, os.ErrNotExist) {
		return report, false, nil
	}
	if err != nil {
		return report, false, err
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, int64(handoffMaxBytes)+1))
	if err != nil {
		return report, false, err
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if len(data) > handoffMaxBytes || dec.Decode(&report) != nil || !report.valid() {
		return handoffRestoreReport{}, false, errHandoffBadReport
	}
	return report, true, nil
}

func (s handoffStore) saveRestore(report handoffRestoreReport) error {
	if report.Steps == nil {
		report.Steps = []handoffRestoreStep{}
	}
	if report.Wakes == nil {
		report.Wakes = []handoffRestoreWake{}
	}
	data, err := json.Marshal(report)
	if err != nil {
		return err
	}
	if !report.valid() {
		return errHandoffBadReport
	}
	return s.replace(s.path("restore.json"), append(data, '\n'))
}

// handoffStepLine is one restore step as restore and status print it.
func handoffStepLine(step handoffRestoreStep) string {
	label := map[string]string{"registration": "registration", "wake-binding": "wake binding", "hub-state": "hub state", "record": "handoff record"}[step.Name]
	switch step.State {
	case handoffRestored:
		return label + ": restored"
	case handoffCorrect:
		return label + ": already correct"
	}
	return label + ": not restored: " + handoffReasons[step.Reason]
}

// handoffDifference counts the ids a snapshot list held that the live list
// does not (closed since) and the ones only the live list holds (new).
func handoffDifference(snapshot, live []string) (closed, added int, fresh map[string]bool) {
	was, is := map[string]bool{}, map[string]bool{}
	for _, id := range snapshot {
		was[id] = true
	}
	fresh = map[string]bool{}
	for _, id := range live {
		is[id] = true
		if !was[id] {
			added++
			fresh[id] = true
		}
	}
	for _, id := range snapshot {
		if !is[id] {
			closed++
		}
	}
	return closed, added, fresh
}

// handoffHubReport prints the hub's live state beside the record's snapshot.
func handoffHubReport(b *strings.Builder, snapshot *handoffSnapshot, live handoffSnapshot) *handoffRestoreHub {
	hub := &handoffRestoreHub{AsOf: live.AsOf, Obligations: len(live.Obligations) + live.ObligationsOmitted,
		Decisions: len(live.Decisions) + live.DecisionsOmitted, Queue: len(live.Queue) + live.QueueOmitted}
	old := handoffSnapshot{}
	if snapshot != nil {
		old, hub.SnapshotAsOf = *snapshot, snapshot.AsOf
		fmt.Fprintf(b, "  read at %s; differences are from the record's snapshot of %s\n", live.AsOf, snapshot.AsOf)
		if old.ObligationsOmitted+old.DecisionsOmitted+old.QueueOmitted+live.ObligationsOmitted+live.DecisionsOmitted+live.QueueOmitted > 0 {
			b.WriteString("  a list left rows out; its differences count only the rows shown\n")
		}
	} else {
		fmt.Fprintf(b, "  read at %s; the record holds no snapshot to compare with (`tt handoff write` stores one)\n", live.AsOf)
	}
	fmt.Fprintf(b, "  helper status: %s", live.HelperStatus)
	if snapshot != nil && old.HelperStatus != live.HelperStatus {
		fmt.Fprintf(b, " (was %s)", old.HelperStatus)
	}
	fmt.Fprintf(b, "\n  %s", handoffWindowLine(live.Window))
	if snapshot != nil && handoffWindowLine(old.Window) != handoffWindowLine(live.Window) {
		fmt.Fprintf(b, " (was: %s)", handoffWindowLine(old.Window))
	}
	b.WriteString("\n")
	ids := func(n int, id func(int) string) []string {
		out := make([]string, n)
		for i := range out {
			out[i] = id(i)
		}
		return out
	}
	since := func(closed, added int) string {
		if snapshot == nil {
			return ""
		}
		return fmt.Sprintf(": %d closed since the record, %d new", closed, added)
	}
	mark := func(fresh bool) string {
		if fresh && snapshot != nil {
			return " (new)"
		}
		return ""
	}
	var fresh map[string]bool
	hub.ObligationsClosed, hub.ObligationsNew, fresh = handoffDifference(ids(len(old.Obligations), func(i int) string { return old.Obligations[i].ID }), ids(len(live.Obligations), func(i int) string { return live.Obligations[i].ID }))
	fmt.Fprintf(b, "  obligations the helper owes: %d%s\n", hub.Obligations, since(hub.ObligationsClosed, hub.ObligationsNew))
	for _, o := range live.Obligations {
		fmt.Fprintf(b, "    %s msg #%d %s from %s due %s %s%s\n", o.ID, o.Message, o.Kind, o.Sender, handoffOr(o.DueAt, handoffNone), o.State, mark(fresh[o.ID]))
	}
	number := func(n int64) string { return strconv.FormatInt(n, 10) }
	hub.DecisionsClosed, hub.DecisionsNew, fresh = handoffDifference(ids(len(old.Decisions), func(i int) string { return number(old.Decisions[i].Message) }), ids(len(live.Decisions), func(i int) string { return number(live.Decisions[i].Message) }))
	fmt.Fprintf(b, "  open owner decisions: %d%s\n", hub.Decisions, since(hub.DecisionsClosed, hub.DecisionsNew))
	for _, d := range live.Decisions {
		fmt.Fprintf(b, "    msg #%d from %s %s%s\n", d.Message, d.Sender, d.State, mark(fresh[number(d.Message)]))
	}
	hub.QueueClosed, hub.QueueNew, fresh = handoffDifference(ids(len(old.Queue), func(i int) string { return old.Queue[i].ID }), ids(len(live.Queue), func(i int) string { return live.Queue[i].ID }))
	fmt.Fprintf(b, "  queue entries launching or running: %d%s\n", hub.Queue, since(hub.QueueClosed, hub.QueueNew))
	for _, q := range live.Queue {
		fmt.Fprintf(b, "    %s %s rev %d order #%d %s%s\n", q.ID, q.Item, q.Revision, q.Order, q.State, mark(fresh[q.ID]))
	}
	return hub
}

// handoffNotesReport prints the instructions and claims a restore leaves with
// the session. They are printed and never acted on, and never fail a restore.
func handoffNotesReport(b *strings.Builder, r handoffRecord, now time.Time) {
	section := func(title, name string, keep func(state string) bool) {
		k, _ := handoffKindNamed(name)
		fmt.Fprintf(b, "%s\n", title)
		shown := 0
		for _, e := range k.list(&r.Notes).Entries {
			if keep(handoffEntryState(e, now)) {
				fmt.Fprintf(b, "  %s\n", handoffEntryLine(k, e, now))
				shown++
			}
		}
		if shown == 0 {
			b.WriteString("  none\n")
		}
	}
	section("instructions still active (read each cited message before relying on it):", "instruction", handoffLive)
	section("instructions expired or revoked: not authority:", "instruction", func(state string) bool { return !handoffLive(state) })
	section("claims still unverified:", "claim", handoffLive)
}

// handoffRefusal is a guard refusal: the guard, why, and what a person could
// run instead. Nothing has been written when one is returned.
func handoffRefusal(guard, reason, instead string) error {
	text := fmt.Sprintf("restore refused by guard %s: %s. Nothing was registered, written or changed.", guard, reason)
	if instead != "" {
		text += " Instead: " + instead
	}
	return errors.New(text)
}

// handoffPendingRefusal is why a helper file's pending registration stops a
// restore, and what to run instead; both are empty when it has none or has
// only this session's own restore, which the register code replays. It makes
// the comparison the register code makes for a conditional registration, so
// restore passes nothing that code then refuses. This session's own plain
// tt helper register is a different request with an unknown outcome: only
// that command can finish it.
func handoffPendingRefusal(f ownerHelperFile, req api.RegisterOwnerHelperRequest, thread, expected, register string) (reason, instead string) {
	if f.PendingRequest == "" {
		return "", ""
	}
	plain := helperRequestHash(req, thread)
	req.ExpectedRunID = expected
	switch f.PendingHash {
	case helperRequestHash(req, thread):
		return "", ""
	case plain:
		return "this session's own `tt helper register` is still pending and its outcome is unknown", "run `tt helper register --task " + f.Task + "` again to finish it"
	}
	return "the helper file holds a pending registration request from another session", register
}

// handoffRestoreCommand makes this session the project's registered owner
// helper when it is the previous helper session's successor, and reports what
// is and is not restored (docs/session-handoff.md). Guards g1 to g7 are all
// checked before anything is written. It registers through tt helper
// register's own code, conditional on the run it read first; it never opens
// or renews a delegation window, acknowledges or answers an obligation,
// changes a queue entry, resumes a retired helper or acts on an instruction.
func handoffRestoreCommand(e env, args []string) error {
	fs := handoffFlags("handoff restore")
	task := fs.String("task", e.task, "project id")
	if err := fs.Parse(args); err != nil || fs.NArg() > 0 {
		return errors.New(handoffUsage)
	}
	if !handoffOn() {
		return handoffOffError()
	}
	if !api.ValidID(*task, "tsk") {
		return errors.New(handoffUsage)
	}
	register := "`tt helper register --task " + *task + "`, the owner's deliberate registration"

	// g2, first half. The helper file is read once, and its run is fixed here
	// as the expected predecessor before tmux, the hub or a lock is touched.
	// Nothing below assigns to expected.
	files, _ := handoffHelperFiles()
	var named []ownerHelperFile
	for _, f := range files {
		if f.Task == *task {
			named = append(named, f)
		}
	}
	switch {
	case len(named) == 0:
		return handoffRefusal("g2 exact candidate", "no owner helper file for this project is on this host", register)
	case len(named) > 1:
		return handoffRefusal("g2 exact candidate", fmt.Sprintf("%d owner helper files name this project", len(named)), register)
	}
	file := named[0]
	expected := file.Run
	if e.hub == "" {
		e.hub = file.Hub
	}
	if e.hub != file.Hub {
		return handoffRefusal("g2 exact candidate", "the owner helper file on this host is for another hub", register)
	}
	runtime, thread, single := sessionHelperThread()
	if !single || !threadIDPattern.MatchString(thread) {
		return handoffRefusal("g2 exact candidate", "this command is not running in one Claude Code or Codex session", "run it in the owner's runtime session")
	}

	// g1: in tmux, in the pane this command runs in, and that session has
	// exactly one pane.
	ctx, cancel := ctxTimeout(15 * time.Second)
	defer cancel()
	session, inTmux, err := currentHelperSession(ctx)
	switch {
	case err != nil:
		return handoffRefusal("g1 in tmux, one pane", err.Error(), "")
	case !inTmux:
		return handoffRefusal("g1 in tmux, one pane", "this command is not running inside tmux, so the session could not be woken", "run it in the helper's tmux session")
	case session.Panes != 1:
		return handoffRefusal("g1 in tmux, one pane", fmt.Sprintf("tmux session %s has %d panes; wake-ups need exactly one", session.Name, session.Panes), "close the other panes")
	}

	// g7: under the pane's interactive Claude Code session, by the process
	// table. A one-shot run started in the helper's pane passes g1 and g2.
	if runtime == "claude" {
		chain, err := handoffProcessChain(ctx, nil)
		if err != nil {
			return handoffRefusal("g7 interactive session", "the process table could not be read, so this command could not be placed under an interactive Claude Code session", "run it in the helper's interactive session")
		}
		if reason := handoffOneShot(chain, handoffClaudePID()); reason != "" {
			return handoffRefusal("g7 interactive session", handoffReasons[reason], "run it in the helper's interactive session, at its own prompt")
		}
	}

	// g2, second half, and g5's pending check.
	registered := file.Runtime == runtime && file.Thread == thread
	if !registered && (file.SessionID != session.ID || file.SessionCreated != session.Created) {
		return handoffRefusal("g2 exact candidate", fmt.Sprintf("the helper file names tmux session %s, not this one: the helper lives elsewhere", handoffOr(file.Session, "none")), register)
	}
	cwd, err := os.Getwd()
	if err != nil {
		return err
	}
	req := helperRegisterRequest(handoffOr(file.Name, api.DefaultOwnerHelperName), runtime, cwd, session, true)
	if reason, instead := handoffPendingRefusal(file, req, thread, expected, register); reason != "" {
		return handoffRefusal("g5 no competing successor", reason, instead)
	}

	// g3, g4 and g6: reads only.
	c, err := e.client(10 * time.Second)
	if err != nil {
		return err
	}
	// The project is read first: a pause closes or holds its agents, and the
	// refusal should name the pause and not what it did to the helper.
	pause, err := c.GetProjectPause(ctx, *task)
	if err != nil {
		return fmt.Errorf("restore could not read the hub: %w. Nothing was registered, written or changed", err)
	}
	if pause.State != api.ProjectPauseActive {
		return handoffRefusal("g6 project active", "the project is "+handoffListed(pause.State, []string{api.ProjectPauseCleanupPending, api.ProjectPausePaused, api.ProjectPauseResuming}), "run it after the project is resumed")
	}
	a, err := c.GetAgent(ctx, *task, file.Agent)
	var httpErr *api.HTTPError
	switch {
	case errors.As(err, &httpErr) && httpErr.Status == 404:
		return handoffRefusal("g3 current run", "the hub has no agent "+file.Agent+" in this project", register)
	case err != nil:
		return fmt.Errorf("restore could not read the hub: %w. Nothing was registered, written or changed", err)
	case a.Role != api.AgentRoleOwnerHelper:
		return handoffRefusal("g3 current run", "the hub's agent "+file.Agent+" is not an owner helper", register)
	case a.RunID != expected:
		// The agent row holds no registration time and the event feed cannot
		// be read boundedly, so none is printed.
		return handoffRefusal("g3 current run", fmt.Sprintf("the hub's helper run is %s, not the helper file's %s: someone registered after this host's file was written; host of the current registration: %s; registration time: unavailable",
			a.RunID, expected, a.Host), "if this session's own registration answer was lost, run `tt helper register --task "+*task+"`")
	}
	switch a.Status {
	case api.AgentRunning, api.AgentDone, api.AgentNeedsInput:
	case api.AgentRetired:
		return handoffRefusal("g4 status", "the owner helper is retired; only tt resume re-enables it", "")
	case api.AgentClosed, api.AgentExited:
		return handoffRefusal("g4 status", "the owner helper is "+a.Status+": registering would create a new agent or run, which is the owner's deliberate act", register)
	default:
		return handoffRefusal("g4 status", "the owner helper is "+handoffListed(a.Status, handoffAgentStatuses), register)
	}

	// g5: take the record lock, then read the helper file again. A different
	// run means another restore or registration completed while this one
	// waited; this command keeps its fixed predecessor and stops.
	store, ok := handoffStoreFor(file.Agent, handoffCommandLockWait)
	if !ok {
		return errors.New("no handoff state directory")
	}
	if err := store.prepare(); err != nil {
		return err
	}
	unlock := store.lock()
	if unlock == nil {
		return handoffRefusal("g5 no competing successor", "another handoff command holds the record lock", "run it again")
	}
	defer unlock()
	handoffTouch(ownerHelperPath(file.Hub, *task))
	again, err := loadOwnerHelperFile(file.Hub, *task)
	switch {
	case err != nil:
		return handoffRefusal("g5 no competing successor", "the helper file could not be read again", register)
	case again.Run != expected || again.Agent != file.Agent || again.Thread != file.Thread || again.Runtime != file.Runtime:
		return handoffRefusal("g5 no competing successor", fmt.Sprintf("another restore or registration completed while this one waited: the helper file no longer names run %s", expected), "run `tt handoff restore --task "+*task+"` again; it will be judged afresh")
	}
	if reason, instead := handoffPendingRefusal(again, req, thread, expected, register); reason != "" {
		return handoffRefusal("g5 no competing successor", reason, instead)
	}

	// The guards have passed. From here every step is reported as restored,
	// already correct or not restored, and restore.json is written.
	now := handoffNow()
	var b strings.Builder
	report := handoffRestoreReport{V: 1, At: handoffStamped(now), Task: *task, Agent: file.Agent, Run: expected, Registration: file.Registration, Runtime: runtime, Session: strings.ToLower(thread)}
	step := func(name, state, reason, detail string) {
		s := handoffRestoreStep{Name: name, State: state, Reason: reason}
		report.Steps = append(report.Steps, s)
		if state == handoffNotRestored {
			report.NotRestored++
		}
		b.WriteString(handoffStepLine(s))
		if detail != "" {
			b.WriteString(": " + detail)
		}
		b.WriteString("\n")
	}
	current := file

	// 1. Registration.
	registeredNow := false
	if registered {
		step("registration", handoffCorrect, "", fmt.Sprintf("this session is the registered helper thread; run %s", expected))
	} else {
		out, err := registerHelperSession(e, helperRegistration{task: *task, name: req.Name, expectedRun: expected})
		var refused *helperExpectedRunRefused
		switch {
		case errors.As(err, &refused) && refused.guard != "":
			// The register code refused under its own lock, before any
			// request: say which of its two reasons the helper file shows.
			if now, err := loadOwnerHelperFile(file.Hub, *task); err == nil && now.Run == expected {
				if reason, instead := handoffPendingRefusal(now, req, thread, expected, register); reason != "" {
					return handoffRefusal("g5 no competing successor", reason, instead)
				}
			}
			return handoffRefusal("g5 no competing successor", fmt.Sprintf("another registration completed while this one waited: the helper file no longer names run %s", expected), "run `tt handoff restore --task "+*task+"` again; it will be judged afresh")
		case errors.As(err, &httpErr):
			step("registration", handoffNotRestored, "hub-refused", err.Error())
		case err != nil:
			step("registration", handoffNotRestored, "register-failed", err.Error())
		default:
			registeredNow = true
			report.Run, report.PreviousRun, report.Registration = out.Agent.RunID, out.Registration.PreviousRunID, out.Registration.ID
			step("registration", handoffRestored, "", fmt.Sprintf("run %s, receipt %s (replaced %s)", out.Agent.RunID, out.Registration.ID, out.Registration.PreviousRunID))
			if current, err = loadOwnerHelperFile(file.Hub, *task); err != nil {
				current = file
			}
		}
	}
	isHelper := registered || registeredNow

	// 2. Wake binding: read back, never written here.
	switch {
	case !isHelper:
		step("wake-binding", handoffNotRestored, "registration-missing", "")
	default:
		var binding runtimeBinding
		path := filepath.Join(relayDir(), bindingKey(runtimeBinding{Hub: current.Hub, Agent: current.Agent})+".binding.json")
		handoffTouch(path)
		data, err := os.ReadFile(path)
		switch {
		case err != nil || json.Unmarshal(data, &binding) != nil:
			step("wake-binding", handoffNotRestored, "no-binding", "run "+register)
		case binding.Thread != thread || binding.Run != current.Run || binding.Agent != current.Agent || binding.Runtime != runtime:
			step("wake-binding", handoffNotRestored, "binding-mismatch", "run "+register)
		case registeredNow:
			step("wake-binding", handoffRestored, "", "the relay binding names this thread and run "+current.Run)
		default:
			step("wake-binding", handoffCorrect, "", "the relay binding names this thread and run "+current.Run)
		}
	}

	// The record: after a registration it takes the new identity and this
	// session's own start, which the hook logged while it was a candidate.
	r, previous, err := store.load()
	if errors.Is(err, errHandoffNoRecord) {
		r, previous, err = handoffRecord{V: 1}, nil, nil
	}
	readable := err == nil
	switch {
	case !readable:
		step("record", handoffNotRestored, "record-unreadable", err.Error())
	case registeredNow:
		r.refreshIdentity(current)
		detail := "identity copied from the helper file; no start was captured for this session, so the last start stamp is left as it was"
		if start, ok := store.latestStart(handoffRecord{}, thread); ok {
			r.Capture.Start, r.Capture.Open = &start, true
			detail = "identity copied from the helper file; this session's start of " + start.Time + " is now the last start"
		}
		if err := store.save(r, previous); err != nil {
			step("record", handoffNotRestored, "record-unreadable", err.Error())
		} else {
			step("record", handoffRestored, "", detail)
		}
	}

	// 3. Hub state, read live. The stored snapshot is not replaced.
	if !isHelper {
		step("hub-state", handoffNotRestored, "registration-missing", "")
	} else if live, err := handoffReadHub(e, current); err != nil {
		step("hub-state", handoffNotRestored, "hub-read-failed", err.Error())
	} else {
		step("hub-state", handoffRestored, "", "")
		report.Hub = handoffHubReport(&b, r.Snapshot, live)
	}

	// 4. Wakes, and 5. instructions and claims.
	if readable {
		b.WriteString("wakes, for this session:\n")
		if !isHelper {
			b.WriteString("  this session is not the registered helper, so no wake can be confirmed for it\n")
		}
		rows, pending, _ := handoffWakeReport(&b, store, r, runtime, strings.ToLower(thread), isHelper, now)
		report.Wakes = rows
		report.NotRestored += pending
		handoffNotesReport(&b, r, now)
	}

	path := store.path("restore.json")
	if err := store.saveRestore(report); err != nil {
		fmt.Print(b.String())
		return fmt.Errorf("the restore report could not be written: %w", err)
	}
	fmt.Fprintf(&b, "report: %s; `tt handoff status --task %s` prints it again\n", path, *task)
	fmt.Print(b.String())
	if report.NotRestored > 0 {
		return fmt.Errorf("restore incomplete: %d not restored (listed above)", report.NotRestored)
	}
	return nil
}

// handoffStatusCommand prints the last restore's report and every wake's
// state for the session asking, so what could not be restored is a command's
// output and not the session's recollection. It reads only this host.
func handoffStatusCommand(e env, args []string) error {
	fs := handoffFlags("handoff status")
	task := fs.String("task", e.task, "project id")
	if err := fs.Parse(args); err != nil || fs.NArg() > 0 {
		return errors.New(handoffUsage)
	}
	agent, err := handoffShowAgent(e, *task)
	if err != nil {
		return err
	}
	store, ok := handoffStoreFor(agent, handoffCommandLockWait)
	if !ok {
		return errors.New("no handoff state directory")
	}
	now := handoffNow()
	var b strings.Builder
	report, found, err := store.loadRestore()
	switch {
	case err != nil:
		return err
	case !found:
		fmt.Fprintf(&b, "No restore has run for %s on this host.\n", agent)
	default:
		fmt.Fprintf(&b, "Last restore: %s, session %s (%s), run %s, %d not restored then.\n", report.At, report.Session, report.Runtime, report.Run, report.NotRestored)
		for _, step := range report.Steps {
			b.WriteString(handoffStepLine(step) + "\n")
		}
		if h := report.Hub; h != nil {
			fmt.Fprintf(&b, "  hub read at %s: %d obligations (%d closed, %d new), %d open owner decisions (%d closed, %d new), %d queue entries (%d closed, %d new)",
				h.AsOf, h.Obligations, h.ObligationsClosed, h.ObligationsNew, h.Decisions, h.DecisionsClosed, h.DecisionsNew, h.Queue, h.QueueClosed, h.QueueNew)
			if h.SnapshotAsOf != "" {
				fmt.Fprintf(&b, ", against the snapshot of %s", h.SnapshotAsOf)
			}
			b.WriteString("\n")
		}
		for _, w := range report.Wakes {
			state := w.State
			switch w.State {
			case handoffAsserted:
				state = "session-asserted, not verified"
			case handoffNotRestored:
				state = "not restored: " + handoffReasons[w.Reason]
			}
			fmt.Fprintf(&b, "  then: %s %s\n", w.ID, state)
		}
	}
	r, _, err := store.load()
	switch {
	case errors.Is(err, errHandoffNoRecord):
		fmt.Fprintf(&b, "No handoff record for %s on this host.\n", agent)
	case err != nil:
		return err
	default:
		// The session asking: this runtime session, or with none, the
		// registered thread the record names.
		runtime, session, single := sessionHelperThread()
		if !single {
			runtime, session = r.Identity.Runtime, r.Identity.Thread
		}
		fmt.Fprintf(&b, "wakes now, for session %s:\n", handoffOr(strings.ToLower(session), "unknown"))
		_, pending, duplicates := handoffWakeReport(&b, store, r, runtime, strings.ToLower(session), false, now)
		fmt.Fprintf(&b, "%d active wakes not restored now; %d duplicate firings recorded.\n", pending, duplicates)
	}
	fmt.Print(b.String())
	if !handoffOn() {
		fmt.Printf("\nSession handoff is off on this host (%s). Nothing updates the record.\n", handoffConfigPath())
	}
	return nil
}
