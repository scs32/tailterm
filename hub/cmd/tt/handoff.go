// Session handoff, stage A (feature wi_3dae763822d9c061). A small structured
// record of what the owner helper session is holding is kept on this host,
// written by `tt handoff note` and `tt handoff write` and stamped by the
// `tt hook handoff` settings hook at session end and compaction. At session
// start the hook prints a bounded note that Claude Code adds to the session's
// context. See docs/session-handoff.md.
//
// Three rules shape everything here:
//
//   - Off unless ~/.config/tailterm/handoff.json holds {"sessionHandoff":"on"}.
//   - The hook never asks the hub, never fails and never writes on PreCompact
//     or SessionEnd, so it cannot block or change a session.
//   - Every stored value is generated by tt or is a validated id, number,
//     time, schedule or fixed-list value. No field accepts words.
//
// Stage B (feature wi_e403542387af7deb) adds `tt handoff restore`, which,
// behind guards and one conditional hub registration, makes a new session the
// registered helper and says what is and is not restored; `tt handoff status`;
// and `tt handoff wake confirm` and `tt handoff wake due`. The hook still
// never registers anything, and tt never creates or lists a cron.

func init() { hookHandlers["handoff"] = handoffHook }

