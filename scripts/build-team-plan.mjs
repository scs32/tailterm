import { rollup } from "rollup";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "hub/internal/teamplan/plan.mjs");
const entry = `
import { exampleTeam } from "./client/team-examples.js";
import { teamLaunchPlan } from "./client/team-launch-plan.js";
import { prepareWorkItemContext } from "./client/work-item-context.js";
import { createHubClient } from "./client/hub-client.js";
async function main() {
  let raw = "";
  for await (const chunk of process.stdin) raw += chunk;
  const input = JSON.parse(raw);
  const client = createHubClient({ baseURL: input.hub, token: input.token,
    fetchImpl: (url, init) => fetch(url, init) });
  if (input.action === "set-orchestrator") {
    process.stdout.write(JSON.stringify(await client.updateTask(input.task,
      { orchestrator: input.orchestrator })) + "\\n");
    return;
  }
  const itemRouting = { workItemTaskId: input.task, workItemId: input.item,
    workItemRevision: input.revision, workOrderTaskId: input.task,
    workOrderMessageSeq: input.order };
  itemRouting.workContextBundle = input.workContextBundle ||
    await prepareWorkItemContext(client, {
      itemTaskId: input.task, itemId: input.item, itemRevision: input.revision,
      workOrderMessage: { taskId: input.task, seq: input.order },
    });
  const plan = teamLaunchPlan({ team: exampleTeam(input.template),
    servers: [{ id: "local", name: input.host }], mainServerId: "local",
    projectFolders: { local: input.cwd }, itemRouting,
    handler: input.handler });
  process.stdout.write(JSON.stringify({ plan, itemRouting }) + "\\n");
}
main().catch((error) => { console.error(error.message); process.exitCode = 1; });
`;
const bundle = await rollup({
  input: "\0team-plan-entry",
  plugins: [
    {
      name: "team-plan-entry",
      resolveId(id, importer) {
        if (id === "\0team-plan-entry") return id;
        if (importer === "\0team-plan-entry" && id.startsWith("./"))
          return resolve(root, id);
        return null;
      },
      load(id) {
        if (id === "\0team-plan-entry") return entry;
      },
    },
  ],
});
const generated = await bundle.generate({
  format: "es",
  inlineDynamicImports: true,
});
const contents =
  "// Generated by scripts/build-team-plan.mjs. Do not edit.\n" +
  generated.output[0].code;
await bundle.close();
if (process.argv.includes("--check")) {
  const existing = await readFile(output, "utf8").catch(() => "");
  if (existing !== contents)
    throw new Error(
      "Embedded team plan is stale; run npm run build:team-plan.",
    );
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, contents);
}
