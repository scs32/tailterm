// ---- Sandbox probes ----

// A sandbox: one temporary root holding the built tt, a copy of the mod, the
// project the session runs in, the ledger, the relay directory and the
// setting file. HOME is the real one, because Claude Code needs its login;
// the transcript folders it writes there are removed at the end.
function newSandbox(t) {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "tt-secret-redaction-")));
  const box = {
    root, values: [], transcripts: new Set(), findings: [], started: Date.now(),
    project: join(root, "project"), mod: join(root, "mod", "secret-redaction"),
    ledger: join(root, "ledger"), relay: join(root, "relay"), setting: join(root, "relay.json"),
    hub: "http://127.0.0.1:9", token: "ttprobe" + randomFrom(ALNUM, 40),
    agent: "agt_" + hex(16), task: "tsk_" + hex(16), run: "run_probe" + hex(8),
  };
  box.values.push(box.token);
  mkdirSync(box.project, { recursive: true });
  mkdirSync(box.relay, { recursive: true });
  cpSync(MOD_DIR, box.mod, { recursive: true });
  const built = run("go", ["build", "-o", join(root, "bin", "tt"), "./cmd/tt"], { cwd: join(ROOT, "hub"), env: process.env, timeout: 300000 });
  assert.equal(built.status, 0, `build tt: ${built.stderr}`);
  return box;
}

// The session's environment, built from nothing. With agent false there is no
// agent, task or run: the owner helper's case.
function sandboxEnv(box, { agent = true, token = box.token } = {}) {
  const vars = {
    PATH: join(box.root, "bin") + ":" + process.env.PATH, HOME: homedir(), TERM: process.env.TERM || "xterm-256color",
    TAILTERM_TOOL_LEDGER_DIR: box.ledger, TAILTERM_RELAY_STATE: box.relay, TAILTERM_REDACT_SETTING_FILE: box.setting,
    TAILTERM_HUB: box.hub, TAILTERM_TOKEN: token,
  };
  if (agent) Object.assign(vars, { TAILTERM_AGENT: box.agent, TAILTERM_TASK: box.task, TAILTERM_RUN: box.run });
  return vars;
}

function setMode(box, mode) {
  writeFileSync(box.setting, JSON.stringify({ claudeSecretRedaction: mode }));
}

function ledgerRows(box, agent) {
  const path = join(box.ledger, agent, "ledger.jsonl");
  if (!existsSync(path)) return [];
  return readFileSync(path, "utf8").split("\n").filter(Boolean).map(line => JSON.parse(line));
}

// Pre-start assertions, as in the parent's b8: no listed variable comes from
// outside the sandbox, every Tailterm path is under its root, and the built
// tt, run with that environment, reads the sandbox setting, loads the
// generated token and writes the sandbox ledger.
function assertSandbox(t, box, vars) {
  for (const name of LISTED_ENV) {
    if (name in vars) assert.ok(name === "TAILTERM_TOKEN" && box.values.includes(vars[name]) && vars[name] !== process.env[name], `pre-start: ${name} comes from outside the sandbox`);
  }
  for (const [name, value] of Object.entries(vars)) {
    if (name.startsWith("TAILTERM_") && value.startsWith("/")) assert.ok(value.startsWith(box.root + sep), `pre-start: ${name} is outside the sandbox`);
  }
  setMode(box, "report");
  const before = ledgerRows(box, box.agent).length;
  const out = spawnSync(join(box.root, "bin", "tt"), ["hook", "redact"], {
    env: sandboxEnv(box), input: JSON.stringify({ v: 1, door: "prompt", tool: "", texts: ["sandbox " + box.token] }), encoding: "utf8", timeout: 10000,
  });
  const rows = ledgerRows(box, box.agent);
  assert.equal(out.status, 0);
  assert.equal(out.stdout, "");
  assert.equal(rows.length, before + 1, "pre-start: the built tt wrote no row to the sandbox ledger");
  assert.deepEqual(rows.at(-1).redactKinds, { "host-credential": 1 }, "pre-start: the built tt did not load the generated token");
  t.diagnostic("pre-start assertions hold: no listed variable inherited; every Tailterm path inside the sandbox; the built tt reads the sandbox setting, loads the generated token and writes the sandbox ledger");
}

// One disposable `claude -p` turn with the mod loaded from the sandbox copy.
// The prompt goes on stdin.
function session(box, vars, prompt, { tools = [], sessionId = randomUUID() } = {}) {
  const args = ["-p", "--output-format", "json", "--model", "haiku", "--plugin-dir", box.mod, "--session-id", sessionId];
  if (tools.length) args.push("--allowedTools", tools.join(","));
  const out = spawnSync("claude", args, { cwd: box.project, env: vars, input: prompt, encoding: "utf8", timeout: 240000 });
  for (const dir of transcriptDirs(box)) box.transcripts.add(dir);
  let result;
  try {
    result = JSON.parse(out.stdout);
  } catch {
    assert.fail(`the disposable session gave no JSON result: exit ${out.status}, ${out.error?.message || ""} (${out.stderr.length} bytes of stderr withheld)`);
  }
  assert.equal(result.is_error, false, `the disposable session failed: ${result.subtype}`);
  return { reply: String(result.result ?? ""), sessionId };
}

// Claude Code names a transcript folder after the project path, which holds
// the sandbox root's unique name.
function transcriptDirs(box) {
  const projects = join(homedir(), ".claude", "projects");
  if (!existsSync(projects)) return [];
  return readdirSync(projects).filter(name => name.includes(box.root.split(sep).pop())).map(name => join(projects, name));
}

// The JSON paths of the strings holding the value.
function paths(v, at, value, out) {
  if (typeof v === "string") {
    if (v.includes(value)) out.push(at);
  } else if (Array.isArray(v)) {
    v.forEach((x, i) => paths(x, `${at}[]`, value, out));
  } else if (v && typeof v === "object") {
    for (const [key, x] of Object.entries(v)) paths(x, `${at}.${key}`, value, out);
  }
  return out;
}

// Records, as observed, which transcript rows and fields hold each value, and
// whether Claude Code's other local folders gained a copy. history.jsonl is
// never read here.
function findings(t, box, label, sessionId, named) {
  const file = [...box.transcripts].map(dir => join(dir, sessionId + ".jsonl")).find(existsSync);
  if (!file) {
    box.findings.push(`${label}: no transcript file found`);
    return;
  }
  const rows = readFileSync(file, "utf8").split("\n").filter(Boolean).map(line => {
    try { return JSON.parse(line); } catch { return {}; }
  });
  const holder = rows.some(row => JSON.stringify(row).includes("[tt-redacted:"));
  for (const [name, value] of Object.entries(named)) {
    const where = [...new Set(rows.flatMap(row => paths(row, "", value, []).map(p => `${row.type}${row.attachment?.type ? " " + row.attachment.type : ""} ${p}`)))];
    box.findings.push(`${label} transcript, ${name}: ${where.length ? where.join("; ") : "not present"}`);
  }
  box.findings.push(`${label} transcript holds a placeholder: ${holder}`);
  const claude = join(homedir(), ".claude");
  const others = [];
  for (const sub of ["paste-cache", "file-history", "session-env", "shell-snapshots", "todos", "sessions"]) {
    walk(join(claude, sub), path => {
      const info = statSync(path);
      if (info.mtimeMs < box.started || info.size > 64 << 20) return;
      const data = readFileSync(path, "utf8");
      if (Object.values(named).some(value => data.includes(value))) others.push(path.slice(claude.length + 1).split(sessionId).join("SESSION"));
    });
  }
  box.findings.push(`${label} other local copies: ${others.length ? others.join(", ") : "none"}`);
  t.diagnostic(box.findings.slice(-Object.keys(named).length - 2).join("\n"));
}

function walk(dir, visit) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path, visit);
    else if (entry.isFile()) visit(path);
  }
}

// Before cleanup no generated value is in the working tree; after it the
// sandbox root and the probe's transcript folders are gone.
function cleanup(t, box) {
  const patterns = join(box.root, "patterns");
  writeFileSync(patterns, box.values.join("\n") + "\n");
  const found = git("grep", "-l", "-I", "--untracked", "-F", "-f", patterns);
  for (const dir of transcriptDirs(box)) box.transcripts.add(dir);
  for (const dir of box.transcripts) rmSync(dir, { recursive: true, force: true });
  rmSync(box.root, { recursive: true, force: true });
  assert.equal(found.status, 1, `a generated value is in the working tree, or the search failed: ${found.stdout}${found.stderr}`);
  assert.equal(existsSync(box.root), false, "the sandbox root remains");
  for (const dir of box.transcripts) assert.equal(existsSync(dir), false, `a probe transcript folder remains: ${dir}`);
  t.diagnostic(`cleanup: none of the ${box.values.length} generated values in the working tree; sandbox root and ${box.transcripts.size} transcript folder(s) removed`);
}

const PROBE_PROMPT = (note, rest) => [
  `My note: ${note} .`,
  "Attached file: @secret.txt",
  `Step 1: run exactly this one Bash command, once, and use no other tool: printf '%s%s\\n' ghp_ ${rest}; exit 3`,
  "It exits non-zero on purpose; do not retry it or run anything else.",
  "Step 2: reply with exactly three lines and nothing else:",
  "A: the token in my note, exactly as you received it",
  "B: the key= line of the attached file, exactly as you received it",
  "C: the command's output, exactly as you received it",
].join("\n");

// a11.1: a prompt, an @file attachment and a failed Bash call, each holding
// its own generated value, in redact mode and then in report mode.
function agentProbe(t, box, mode) {
  const note = newToken(), file = newToken(), printed = newToken();
  box.values.push(note, file, printed);
  writeFileSync(join(box.project, "secret.txt"), `key=${file}\n`);
  setMode(box, mode);
  const vars = sandboxEnv(box);
  const before = ledgerRows(box, box.agent).length;
  const { reply, sessionId } = session(box, vars, PROBE_PROMPT(note, printed.slice(4)), { tools: ["Bash"] });
  const rows = ledgerRows(box, box.agent).slice(before).filter(row => row.outcome === "mod_scan");
  const named = { "prompt value": note, "file value": file, "printed value": printed };
  const inReply = Object.fromEntries(Object.entries(named).map(([name, value]) => [name, reply.includes(value)]));
  t.diagnostic(`a11.1 ${mode}: value in reply ${JSON.stringify(inReply)}; placeholders in reply ${reply.split(HOLDER).length - 1}; mod_scan rows ${JSON.stringify(rows.map(r => [r.reportTag, r.tool, r.redactMode, r.redactKinds]))}`);
  findings(t, box, `a11.1 ${mode}`, sessionId, named);
  for (const door of ["prompt", "attachment", "tool-result"]) {
    const row = rows.find(r => r.reportTag === door && r.redactKinds?.["github-token"] >= 1);
    assert.ok(row, `${mode}: no mod_scan row counting the value on the ${door} door`);
    assert.equal(row.redactMode, mode);
    assert.equal(row.redactSkip, undefined);
    if (door === "tool-result") assert.equal(row.tool, "Bash");
  }
  if (mode === "redact") {
    for (const [name, value] of Object.entries(named)) assert.equal(reply.includes(value), false, `redact: the ${name} reached the reply`);
    assert.ok(reply.includes(HOLDER), "redact: the reply holds no placeholder");
  } else {
    for (const [name, value] of Object.entries(named)) assert.equal(reply.includes(value), true, `report: the reply lacks the ${name}`);
    assert.equal(reply.includes(HOLDER), false, "report: the reply holds a placeholder");
  }
}

// a11.2: no agent, task or run; the owner helper registered from the session
// under the id the probe gives it, written as tt helper register would.
function helperFile(box, thread) {
  const file = { hub: box.hub, task: "tsk_" + hex(16), agent: "agt_" + hex(16), name: "owner-helper", run: "run_helper" + hex(8), thread, runtime: "claude" };
  const name = `${createHash("sha256").update(file.hub).digest("hex")}-${file.task}.owner-helper.json`;
  writeFileSync(join(box.relay, name), JSON.stringify(file), { mode: 0o600 });
  return { file, path: join(box.relay, name) };
}

function helperProbe(t, box, label, { register }) {
  const value = newToken();
  box.values.push(value);
  setMode(box, "redact");
  const sessionId = randomUUID();
  const helper = register === "none" ? null : helperFile(box, register === "this" ? sessionId : randomUUID());
  const ledgerBefore = existsSync(box.ledger) ? readdirSync(box.ledger).map(a => [a, ledgerRows(box, a).length]) : [];
  try {
    const { reply } = session(box, sandboxEnv(box, { agent: false }), `My note: ${value} .\nReply with only the token in my note, exactly as you received it, and nothing else.`, { sessionId });
    const ledgerAfter = readdirSync(box.ledger).map(a => [a, ledgerRows(box, a).length]);
    const helperRows = helper ? ledgerRows(box, helper.file.agent) : [];
    t.diagnostic(`a11.2 ${label}: value in reply ${reply.includes(value)}; placeholder in reply ${reply.includes(HOLDER)}; helper ledger rows ${JSON.stringify(helperRows.map(r => [r.task === helper?.file.task, r.reportTag, r.redactMode, r.redactKinds]))}`);
    findings(t, box, `a11.2 ${label}`, sessionId, { "prompt value": value });
    if (register === "this") {
      assert.equal(reply.includes(value), false, `${label}: the value reached the reply`);
      assert.ok(reply.includes(HOLDER), `${label}: the reply holds no placeholder`);
      const row = helperRows.find(r => r.outcome === "mod_scan" && r.reportTag === "prompt");
      assert.ok(row, `${label}: no mod_scan row in the helper's sandbox ledger`);
      assert.equal(row.task, helper.file.task);
      assert.equal(row.run, helper.file.run);
      assert.equal(row.redactMode, "redact");
      assert.equal(row.redactKinds?.["github-token"], 1);
    } else {
      assert.equal(reply.includes(value), true, `${label}: the reply lacks the value`);
      assert.deepEqual(ledgerAfter, ledgerBefore, `${label}: a ledger row was written`);
    }
  } finally {
    if (helper) rmSync(helper.path, { force: true });
  }
}

test("sandbox probes: a disposable claude -p session with the mod and a built tt", { timeout: 30 * 60 * 1000 }, async (t) => {
  if (!OPTED_IN) return t.skip(NOT_OPTED_IN);
  requireClaude(t);
  const box = newSandbox(t);
  try {
    assertSandbox(t, box, sandboxEnv(box));
    await t.test("a11.1 redact: the prompt, the @file attachment and the failed Bash call reach the model rewritten", (t) => agentProbe(t, box, "redact"));
    await t.test("a11.1 report: the values reach the model and the sandbox ledger counts them", (t) => agentProbe(t, box, "report"));
    await t.test("a11.2 owner helper of this session: rewritten, row in the helper's ledger", (t) => helperProbe(t, box, "helper of this session", { register: "this" }));
    await t.test("a11.2 no helper file: unchanged, no row", (t) => helperProbe(t, box, "no helper file", { register: "none" }));
    await t.test("a11.2 helper of another session: unchanged, no row", (t) => helperProbe(t, box, "helper of another session", { register: "other" }));
    // The real tool ledger gained nothing for the probe's identities.
    assert.equal(existsSync(join(homedir(), ".local", "state", "tailterm", "tool-ledger", box.agent)), false, "the real tool ledger gained a directory for the probe's agent");
    t.diagnostic("findings, as observed:\n" + box.findings.join("\n"));
  } finally {
    cleanup(t, box);
  }
});

// a11.3, by hand only: an interactive session on a private tmux socket in
// redact mode. A prompt queued during a running Bash sleep and a bracketed
// paste each carry the sandbox TAILTERM_TOKEN, a random string of lowercase
// letters and digits that tt matches as a host value, so no secret-shaped
// value enters the owner's real prompt history. Interactive sessions write
// every prompt to ~/.claude/history.jsonl, which live sessions append to; the
// test reads it only to count the lines it left, and never changes it.
test("interactive probe: queued and pasted prompts reach the model rewritten", { timeout: 15 * 60 * 1000 }, async (t) => {
  if (!INTERACTIVE) return t.skip(NOT_INTERACTIVE);
  requireClaude(t);
  const box = newSandbox(t);
  const token = randomFrom("abcdefghijklmnopqrstuvwxyz0123456789", 24);
  box.values.push(token);
  const socket = "tt-redact-" + hex(8);
  const tmux = (...args) => spawnSync("tmux", ["-L", socket, ...args], { encoding: "utf8", timeout: 10000 });
  const screen = () => tmux("capture-pane", "-p", "-t", "probe").stdout || "";
  const sleep = (ms) => new Promise(done => setTimeout(done, ms));
  const waitFor = async (check, ms, what) => {
    for (const end = Date.now() + ms; Date.now() < end; await sleep(1000)) if (check(screen())) return;
    assert.fail(`interactive: timed out waiting for ${what}`);
  };
  const sessionId = randomUUID();
  try {
    setMode(box, "redact");
    const vars = sandboxEnv(box, { token });
    assertSandbox(t, box, vars);
    setMode(box, "redact");
    const command = ["env", "-i", ...Object.entries(vars).map(([k, v]) => `${k}=${v}`), "claude", "--plugin-dir", box.mod, "--model", "haiku", "--allowedTools", "Bash", "--session-id", sessionId];
    assert.equal(tmux("new-session", "-d", "-s", "probe", "-x", "200", "-y", "50", "-c", box.project, ...command).status, 0, "interactive: tmux did not start");
    await sleep(5000);
    // The folder trust question, when it is asked, is answered yes.
    if (screen().toLowerCase().includes("trust")) tmux("send-keys", "-t", "probe", "Enter");
    await sleep(3000);
    tmux("send-keys", "-t", "probe", "-l", "Run this Bash command and then say finished: sleep 15; echo slept");
    tmux("send-keys", "-t", "probe", "Enter");
    await sleep(7000);
    tmux("send-keys", "-t", "probe", "-l", `Queued note: ${token} . Reply with the token in this queued note, exactly as you received it.`);
    tmux("send-keys", "-t", "probe", "Enter");
    await waitFor(text => text.includes(HOST_HOLDER), 180000, "the queued reply");
    const lines = Array.from({ length: 16 }, (_, i) => (i === 14 ? `key=${token}` : `line ${i + 1} = value ${i + 1}`));
    writeFileSync(join(box.root, "paste.txt"), lines.join("\n"));
    tmux("load-buffer", "-b", "probe", join(box.root, "paste.txt"));
    tmux("send-keys", "-t", "probe", "-l", "Pasted config follows. ");
    tmux("paste-buffer", "-p", "-b", "probe", "-t", "probe");
    tmux("send-keys", "-t", "probe", "-l", " Reply with only the key= line from my pasted config, exactly as you received it.");
    tmux("send-keys", "-t", "probe", "Enter");
    await waitFor(text => text.split(HOST_HOLDER).length - 1 >= 2, 180000, "the pasted reply");
    tmux("send-keys", "-t", "probe", "-l", "/exit");
    tmux("send-keys", "-t", "probe", "Enter");
    await sleep(3000);
    // The model's replies, read from the transcript: the screen draws a
    // queued or pasted prompt as typed, before its rewrite.
    for (const dir of transcriptDirs(box)) box.transcripts.add(dir);
    const file = [...box.transcripts].map(dir => join(dir, sessionId + ".jsonl")).find(existsSync);
    assert.ok(file, "interactive: no transcript file");
    const replies = readFileSync(file, "utf8").split("\n").filter(Boolean).map(line => JSON.parse(line))
      .filter(row => row.type === "assistant").flatMap(row => (row.message?.content || []).filter(b => b.type === "text").map(b => b.text));
    t.diagnostic(`a11.3 replies (value masked): ${JSON.stringify(replies.map(r => r.split(token).join("<VALUE>")))}`);
    findings(t, box, "a11.3", sessionId, { "queued and pasted value": token });
    assert.equal(replies.some(r => r.includes(token)), false, "interactive: the value reached a reply");
    assert.ok(replies.filter(r => r.includes(HOST_HOLDER)).length >= 2, "interactive: fewer than two replies hold the placeholder");
  } finally {
    tmux("kill-server");
    const left = existsSync(join(homedir(), ".claude", "history.jsonl"))
      ? readFileSync(join(homedir(), ".claude", "history.jsonl"), "utf8").split("\n").filter(line => line.includes(token)).length : 0;
    t.diagnostic(`a11.3 left ${left} line(s) holding the random value in ~/.claude/history.jsonl; docs/claude-mods-secret-redaction.md says how to remove them`);
    cleanup(t, box);
    assert.notEqual(tmux("has-session").status, 0, "interactive: the probe's tmux server remains");
  }
});
